// Olympic 各店（キッチンカー行 平日3,000円）
for (const p of pub) if (/^Olympic /.test(p.title)) weekday[p.title] = 3000

const vals = []
for (const p of pub) if (weekday[p.title] != null) vals.push([p.title, weekday[p.title]])
console.log('平日固定額あり:', vals.length, '件  （記事の主張: 59件）')

const med = a => { const s = [...a].sort((x, y) => x - y); const n = s.length
  return n % 2 ? s[(n - 1) / 2] : (s[n / 2 - 1] + s[n / 2]) / 2 }
const tally = a => { const m = {}; for (const v of a) m[v] = (m[v] || 0) + 1
  return Object.entries(m).sort((x, y) => x[0] - y[0]).map(([k, v]) => `${Number(k).toLocaleString()}円:${v}件`).join('  ') }

const scen = {
  'A 現行（尼涼祭=3,000円）': vals.map(v => v[1]),
  'B 指摘案（尼涼祭=2,000円）': vals.map(([t, v]) => t.includes('尼涼') ? 2000 : v),
  'C 除外（尼涼祭を集計から外す）': vals.filter(([t]) => !t.includes('尼涼')).map(v => v[1]),
}
for (const [name, a] of Object.entries(scen)) {
  console.log(`\n--- ${name} ---`)
  console.log('  件数:', a.length, ' 中央値:', med(a).toLocaleString(), ' 最低:', Math.min(...a).toLocaleString(), ' 最高:', Math.max(...a).toLocaleString())
  console.log('  分布:', tally(a))
}

