// 期間価格のため日額表から外れるもの: #23 美食EXPO「2日間／7万円」（固定制だが1日額なし）

const med = a => { const s=[...a].sort((x,y)=>x-y); const n=s.length; return n%2? s[(n-1)/2] : (s[n/2-1]+s[n/2])/2 }
const dist = a => { const d={}; for(const v of a) d[v]=(d[v]||0)+1
  return Object.entries(d).sort((x,y)=>x[0]-y[0]).map(([k,v])=>`${Number(k).toLocaleString()}円:${v}件`).join('  ') }
const show = (label, arr) => {
  console.log(`  ${label}  件数 ${arr.length} / 中央値 ${med(arr).toLocaleString()}円 / 最低 ${Math.min(...arr).toLocaleString()}円 / 最高 ${Math.max(...arr).toLocaleString()}円`)
  console.log(`     ${dist(arr)}`)
}

