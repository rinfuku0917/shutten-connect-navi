const med = a => { const s=[...a].sort((x,y)=>x-y); const m=s.length>>1
  return s.length%2 ? s[m] : (s[m-1]+s[m])/2 }
const cnt = a => { const m={}; for (const v of a) m[v]=(m[v]||0)+1
  return Object.entries(m).sort((x,y)=>x[0]-y[0]).map(([k,v])=>`${(+k).toLocaleString()}円:${v}件`).join(' ') }
const show = (label, rows) => {
  const wd = rows.map(r=>r[0]), we = rows.map(r=>r[1])
  console.log(`\n■ ${label}  n=${rows.length}`)
  for (const [n,a] of [['平日',wd],['週末',we]])
    console.log(`  ${n}  中央値 ${med(a).toLocaleString()}円 / 最低 ${Math.min(...a).toLocaleString()}円 / 最高 ${Math.max(...a).toLocaleString()}円`)
  console.log('  平日内訳:', cnt(wd))
  console.log('  週末内訳:', cnt(we))
}

