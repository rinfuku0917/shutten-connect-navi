-- 形態ごとの出店料に「土日祝の金額」を足す。列の追加はない（jsonb の中身だけ）。
--
-- なぜ:
--   形態ごとに金額を1組しか入れられず、「平日3,000円・土日4,500円」のような
--   案件を入れられなかった。実際に運用で詰まったのがこの点で、
--   「片方のみは設定できるが、もう一方の条件設定の箇所が無い」という報告になった。
--
-- なぜ「平日」の欄を作らず、既存の placeFee／companyFee を平日として使うのか:
--   分けない案件のほうが多い。欄を2つにすると、分けない案件で
--   どちらに入れるのか迷う。既存の欄を「金額（分けるときは平日）」、
--   新しい weekend を「土日祝の金額」にすると、
--   分けない案件は今までと同じ入力で済み、途中で分けることにしても
--   すでに入れた値が消えない。既存データの書き換えも要らない。
--
-- あわせて、選べる形態に「テント・ブース」を足した。
-- イベント出店で車を使わない出店（区画だけ借りてテントを張る）があり、
-- キッチンカーとは料金が違う。
--
-- 形（app/lib/placeFee.ts の FormatFees が唯一の正）:
--   {
--     "キッチンカー": {
--       "placeFee": 3000,        平日に取引先へ渡す額（土日祝を入れないときは全日）
--       "companyFee": 0,         平日の弊社の固定額
--       "weekend": {             土日祝だけ額が違うときに入れる。祝日も土日と同じ扱い
--         "placeFee": 4500,      空欄にした項目は、上の平日の額がそのまま使われる
--         "companyFee": null
--       },
--       "sharePct": 0,           取引先の歩合（売上の%）。日によって変えられない
--       "companySharePct": 10,   弊社の歩合（売上の%）
--       "note": "3m×5m・電源あり", 区画の条件（画面にそのまま出す）
--       "dows": [0, 6]           出られる曜日。空なら案件の日程すべて
--     },
--     "物販": { ... }, "催事PR": { ... }, "テント・ブース": { ... }
--   }
--
-- 金額の優先順位（app/admin/page.tsx の calcFees と
-- app/dashboard/seller/page.tsx の calcFee で必ず同じ順にする）:
--   1. 形態ごとの額（土日祝を分けていれば、その日に合う額）
--   2. 日程に入れたその日の額（places.schedule）
--   3. 案件の平日／土日祝の額（places.day_type_fees）
--   4. 案件全体の固定額
--
--   形態をいちばん強くしている。以前は 2 を先に見ていたため、
--   「催事PRに18,000円を入れたのに、申込画面の各日は3,000円/4,500円のまま」
--   という状態になっていた。日程の金額はキッチンカー向けに入れたものなので、
--   形態に金額を入れたらそちらが効くのが、入力した人の期待に合う。
--   特定の日だけ別の額にしたい場合は、形態の金額を空欄にして
--   日程のその日に入れる（空欄の項目はひとつ下に落ちる）。

comment on column public.places.format_fees is
  '形態ごとの出店料と条件。{"キッチンカー":{placeFee,companyFee,weekend:{placeFee,companyFee},sharePct,companySharePct,note,dows},...}。'
  '形態は キッチンカー／物販／催事PR／テント・ブース。placeFee は平日（weekend 未設定なら全日）、'
  'weekend は土日祝だけ額が違うときに入れる。優先順位は 形態→日程の各日→案件の平日土日→案件全体';

