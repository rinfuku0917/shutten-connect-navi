出店者の募集、条件のやり取り、当日の連絡は運営が窓口になります。個別に何件もメールをやり取りする必要はありません。

書類（営業許可証・PL保険・検体検査）の確認も運営が行います。何を確認しているかは[キッチンカー出店に必要な書類](/blog/kitchen-car-required-documents)にまとめています。

### 契約と近隣の確認

始める前に確認しておくことがいくつかあります。契約書に入れる項目、賠償の範囲、ゴミの扱い、近隣への説明、雨天時の扱い。

駐車場を貸す場合に必要な手続きは[駐車場をキッチンカーに貸すには](/blog/renting-parking-space)に、曜日と時間帯の決め方は[定期開催の曜日と時間帯の決め方](/blog/regular-event-schedule)に分けてまとめました。

