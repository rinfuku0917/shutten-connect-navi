## 空きスペースでキッチンカーが成り立つ理由

キッチンカーは、車そのものが店舗です。厨房・電源・給排水・冷蔵設備を積んで走ってきます。

つまり、貸す側が用意するものは**区画と、そこに人がいる理由**だけです。テナントを入れるときのような内装工事、給排水の引き込み、区画の仕切り——どれも要りません。

これは遊休スペースと相性がよい条件です。建て替えまでの2年、月極が埋まらない数区画、催事のない平日の店先。**期限があっても、面積が小さくても成り立ちます。**

出店コネクトナビで募集中の110件のうち、**99件が常設**です。単発のイベントは11件しかありません。一度条件が決まると、続く形が主流になっています（2026年9月12日時点）。

## 決めることは4つ

### 1. 場所の条件

必要なのは、キッチンカー1台が停まれる区画です。

1tトラック型で**約3.5m×6m**が目安になります。軽自動車を改造した車両ならもっと小さく収まります。区画の広さと、車両が入ってくる経路（入口の幅と高さの制限）を確認してください。

電源は、あれば喜ばれますが**必須ではありません**。多くの車両が発電機を積んでいます。給排水も車載です。用意できるものと、できないものを最初に伝えれば、それに合う車両が応募してきます。

### 2. 曜日と時間

「毎週水曜の11時から14時」のように決めて募集します。まとめて1か月ぶんの日程を登録することもできます。

人が通る時間帯に合わせるのが基本です。住宅地なら夕方、オフィス街なら昼、商業施設なら土日。

### 3. 出店料の形

ここがいちばん聞かれるところです。出店料の決め方には3つの形があります。

| 形 | 内容 | 募集中の件数 |
|---|---|---|
| 固定 | 1日あたり決まった額 | 52件 |
| 歩合 | 売上に対する割合 | 43件 |
| 併用 | 固定＋歩合 | 9件 |

**歩合を選べば、貸す側の持ち出しは0円です。** 売れなければ発生せず、売れたら分け合う形になります。

率の設定は、**歩合が含まれる案件52件**（歩合のみ43件と併用9件の合計）で数えると、**35件が10%**でした。15%が13件、20%が4件で、10%が最も多い設定です。

固定額で決める場合、募集中の案件では**平日・週末とも1日5,000円が中央値**です。平日の下限は3,000円、週末の下限は4,500円でした。

どちらがよいかは、人の通り方で変わります。売上の読みが立たない場所なら歩合、確実に人が通る場所なら固定が向きます。**迷ったら「応相談」で出すこともできます**（募集中6件がこの形です）。

### 4. どんなジャンルを入れるか

登録している1,386店のジャンルは次のようになっています。

- 食事 603店
- スイーツ 512店
- ドリンク 478店
- 物販 36店

**2つ以上のジャンルを持つ店が525店**あります。「食事とスイーツの両方」のように、時間帯で売り方を変えられる車両です。

メニューは全体で**3,695件**登録されていて、そのすべてに価格が入っています。写真つきのメニューは2,834件です。応募が来たときに、何をいくらで売る車なのかを事前に見て決められます。

## 応募が集まりやすい条件

同じような場所でも、条件の書き方で応募の集まり方が変わります。募集中の案件を見ると、次の傾向がありました。

**税の扱いを書いておく。** 募集中110件のうち**72件が、出店料の税の扱いを明記**しています。「5,000円（税込）」「売上の10%＋税」のように書いてある案件です。出店者にとっては手元に残る額が変わるので、書いていないと問い合わせが1往復増えます。決めて書いてしまうのが早いです。

**固定と歩合を混ぜるのは、大きい施設向け。** 併用（固定＋歩合）は9件ありますが、**そのうち8件が商業施設**です。単独の空きスペースで始めるなら、固定か歩合のどちらかに絞るほうが条件が伝わりやすくなります。

**続けられる形にする。** 募集中110件のうち99件が常設です。「まず1回」でも構いませんが、出店者は仕入れと人の手配をして来ます。**続く見込みがあると分かると応募が集まりやすくなります。** 「毎週水曜」「第2・第4土曜」のように決めて出すのが定石です。

## 収益の見方

歩合10%で、1日の売上が5万円だったとします。その日の出店料は5,000円です。週1回なら月に約2万円、週2回なら約4万円。

固定5,000円/日で週2回なら、月に約4万円です。

月極駐車場の1区画の相場と比べると、**1区画でその水準に届く**計算になります。しかも月極と違い、営業していない時間は区画が空いているので、平日の日中だけ貸して夜は別の用途に使う、といった組み方もできます。

もうひとつ見落とされやすいのが、**人が集まること自体の効果**です。店舗の前に貸す場合、キッチンカーの客がそのまま店に入ります。集合住宅なら住民向けの便益になります。出店料だけが収益ではありません。

商業施設やオフィスビルで実際にどう効いているかは[商業施設・オフィスビルにキッチンカーを導入する効果](/blog/host-fee-setting-guide)にまとめています。

