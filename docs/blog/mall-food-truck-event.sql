### なぜ併用が選ばれるのか

以下は**データではなく、条件の設計としての説明**です。

商業施設は、来客数は多いが**日によって大きく振れる**場所です。晴れた土曜と雨の平日では売上が何倍も違い、セールの有無でも客足が変わります。

固定制だと、売れない日に出店者が損をします。歩合制だと、当たった日でも施設側の取り分が読めません。**併用は、その両方をならす形**です。

実際に使われている併用（商業施設8件）は2通りありました。

| 形 | 実例 | 件数 |
|---|---|---|
| **足し算型** | 3,000円＋売上の15％／4,000円＋売上の10％ | 6件 |
| 最低保証型 | 売上の20％。ただし平日2,000円・休日7,500円は必須 | 2件 |

**足し算型**は、下限を固定で確保したうえで、売れた分だけ上乗せする形です。出店者から見ると「最低これだけは払う」が分かるので、条件を読みやすくなります。

**最低保証型は2件とも同じ系列の同じ文面**でした。歩合が主で、売上が伸びなかった日だけ下限が働きます。毎回「歩合と下限のどちらが高いか」を比べる必要があるので、**運用の手間は足し算型のほうが軽い**です。

