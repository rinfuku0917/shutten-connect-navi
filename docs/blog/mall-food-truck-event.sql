## 何を売る車を入れるか

判断の基準はひとつです。**その商品が、館内で買えるかどうか。**

商業施設にはテナントの飲食店やフードコートが入っています。館内で買えるものを外で安く売れば、テナントの売上を食うだけです。**テナントから苦情が出ると、催事そのものが続かなくなります。**

- ラーメン、カレー、丼もの … **フードコートと正面からぶつかる**
- クレープ、コーヒー、生ジュース … 館内に無いことが多く、持ち歩けるので回遊も止めない

売り場との競合の考え方は[スーパーの駐車場にキッチンカーを誘致するには](/blog/supermarket-food-truck)に詳しく書きました。

## 何台から始めるか

**まず1台**をおすすめします。

複数台を並べると賑わいは出ますが、1台あたりの売上は下がります。**売上が下がると、次から来てくれません。** 良い出店者を確保するほうが、台数を増やすより効きます。

3か月ほど1台で回して、来客の反応と売上を見てから増やしてください。判断の材料はこの3つです。

1. **行列ができているか** … できていれば台数を増やす余地がある
2. **テナントから苦情が出ていないか**
3. **出店者が続けて入りたいと言っているか** … 言われなければ条件が合っていない

## 手続きと注意点

契約書に入れる項目、保険の確認、電源と給排水、近隣への説明。ここは駐車場を貸す場合と共通するので、[駐車場をキッチンカーに貸すには](/blog/renting-parking-space)にまとめました。

商業施設で特に気をつけたいのは**消防法まわり**です。屋内や屋根のある場所で火気を使う場合、消防署への届出や、消火器の配置が求められることがあります。**設置場所が決まった時点で、管轄の消防署に相談**してください。

