## キッチンカーが学食の混雑とメニューの単調さを解消する

### 昼の列を、学食の外に分ける

学食が混むのは、全員が同じ時間に同じ場所へ向かうからです。キッチンカーは屋外で注文と受け渡しを済ませるので、**列がそのまま食堂の外に移ります。** 買った学生は中庭やベンチ、教室で食べるため、食堂の席も空きます。

厨房・給排水・冷蔵設備は車に積んで来ます。**学校が用意するのは、車1台ぶんの区画だけ**です。工事も設備投資も要りません。

### 曜日ごとに違う車で、メニューが日替わりになる

学食のメニューは、限られた厨房と人手で回すぶん固定化します。キッチンカーはここに強い。**火曜はケバブ、木曜はカレー、金曜はクレープ**と曜日ごとに別の車を割り振れば、学生にとっては毎週メニューが入れ替わる昼休みになります。

呼べる相手も十分にいます。出店コネクトナビで出店者ページを公開しているのは**1,386店**、そのうち**東京を対応エリアに入れているのが765店**です。ジャンルは食事603店・スイーツ512店・ドリンク478店（複数選択のため合計は店数を超えます）。昼食の車と、午後の休み時間に向くスイーツやドリンクの車を組み合わせられます。

### 学生と教職員の「昼の楽しみ」になる

キャンパスにキッチンカーが来ると、昼休みの景色が変わります。**「今日は何が来ている？」が会話になり、昼の行列が名物になります。** 学外に食べに出る時間のない教職員にとっても、頼れる昼食の選択肢です。

## 【実データ】最も多く掲載してきた場所が学校

出店コネクトナビでこれまでに掲載した案件は**306件**（募集終了を含む）。そのうち**130件が学校**で、場所の種類として最も多い数です。構内ランチは、キッチンカーにとって定番の出店先です。

いま募集中の110件のうち、学校は**31件**。内訳は次のとおりです。

| 切り口 | 募集中の学校31件のうち |
|---|---|
| 専門学校・学院 | 19件 |
| 大学・短大 | 11件 |
| 常設（続けて出店する募集） | 28件 |
| 東京都の案件 | 16件 |

※学校の種類は案件名で分けました。件数は募集の数です。

**専門学校・学院が19件。** 看護・美容・保育・IT・医療系と分野は幅広く、学食を持たない学校、昼休みが短く外へ食べに出られない学校でこそ、構内に車が来る効果が大きく出ます。

**大学・短大は11件。** 敷地が広く学食から離れた棟がある大学や、郊外にあって周りに飲食店が少ないキャンパスで、とくに力を発揮します。

そして**31件のうち28件が常設**です。一度来てもらって終わりではなく、「この曜日はキッチンカーの日」として続けるのが学校の基本形です。

## 出店料は31件すべて歩合。学校の持ち出しは0円

学校の案件で、いちばんはっきり出た数字がこれです。

| 出店料の決め方 | 募集中の学校31件 |
|---|---|
| **歩合（売上の◯%）** | **31件** |
| 固定（1日◯円） | 0件 |
| 固定＋歩合の併用 | 0件 |
| 応相談 | 0件 |

**31件すべてが歩合**です。出店料は出店者が売上の中から払うもので、**学校が予算を組む必要はありません。** 売れた日は売れた分だけ受け取り、雨で客足が落ちた日も学校に負担は生じません。

率の内訳は次のとおりです。

| 歩合の率 | 募集中の学校31件 |
|---|---|
| **売上の10%** | **29件** |
| 売上の15% | 2件 |

**10%が標準**です。15%の2件は、学会の大会と学園祭という単発の催しでした。募集要項には「売上の10%＋税」のように、税の扱いまで書いておくのが定番です。

なお、ここでの率は**出店者が支払う側の条件**です。仲介を通す場合、学校が受け取るのはここから手数料を引いた額になります。

募集中110件の全体では固定のみが52件で最も多く、スーパーは35件のうち32件が固定です。その中で**学校は、歩合に振り切った場所**です。予算の費目がなくても始められ、学期によって客足が振れても双方が無理なく続けられます。歩合が学校で選ばれる理由は[キッチンカーを無料で呼ぶには](/blog/invite-food-truck-free)に、率や金額の相場全体は[キッチンカーの出店料の相場](/blog/food-truck-fee-guide)にまとめています。

## 昼休みに合わせて、時間帯と曜日を決める

### 時間帯は「昼の山を挟む」

募集中の学校31件のうち、出店の時刻まで書かれていた6件はこうなっています。

| 案件 | 時間帯 |
|---|---|
| 埼玉の看護学校 | 12:00〜13:00 |
| 大阪の大学 | 11:00〜14:00 |
| 大阪の大学のキャンパス | 11:00〜15:00 |
| 都内の薬科大学 | 10:20〜16:00 |
| 都内の保育専門学校 | 11:30〜17:30 |
| 神奈川の学会の大会（単発） | 10:30〜16:00 |

型は3つです。

- **昼休みに絞る**（12:00〜13:00）… 昼休みが一斉の学校向け。短い時間に売上が集中します
- **昼の山を挟む**（11:00〜14:00）… 時間割がずれる大学でも昼の山を取りこぼさない、いちばん組みやすい形です
- **夕方まで通す**（〜16:00、〜17:30）… 午後の休み時間や放課後の軽食・ドリンクまで拾います

迷ったら**11:00〜14:00**から始めてください。

### 曜日は「週1回から、学事暦に合わせて」

曜日の書き方は学校ごとに違います。実際の募集要項から抜き出しました。

- 「毎週火曜日」（都内の専門学校）
- 「毎週火曜日、木曜日、金曜日（祝日、長期休みは除く）」（埼玉の看護専門学校）
- 「平日全日／月〜金」（神奈川の大学）
- 「火、水、金／月に１回出店／スポットOK」（都内の専門学校）
- 「毎月第一第三水曜日」（大阪の大学）
- 9月末から10月の毎週金曜日を日付で指定（大阪の大学のキャンパス）

定石は、**週1回から始めて、手応えを見て曜日を増やす**ことです。「祝日、長期休みは除く」と最初から書いておけば、休暇中の扱いで迷いません。曜日ごとに別の車を入れれば、メニューの日替わりも同時にかないます。曜日と時間帯の考え方は[定期開催の曜日と時間帯の決め方](/blog/regular-event-schedule)でも詳しく扱っています。

## 構内に入れるまでの段取り

### 置き場所は「学生の通り道」

正門から校舎へ向かう動線、中庭、学食の近く。**人が必ず通る場所に置くほど売れて、出店が長く続きます。** 車両が構内に入る経路（門の幅・高さ）と、出店中に歩行者と車が交わらないかを確認してください。

### 学食と「かぶらない」ジャンルを選ぶ

学食を委託している場合は、事前に話を通しておくと進みが早くなります。**学食にない丼もの・エスニック・スイーツ**を入れれば、学食の客を奪うのではなく、昼の選択肢そのものが増えます。出店コネクトナビに登録されたメニュー3,695件には、すべて価格が入っています。**学生が払いやすい価格帯の車を、事前に見て選べます。**

### 書類を確認する

営業許可証、PL保険、検体検査の結果。学生と教職員が毎週口にするものなので、ここは必ず確認します。何を見ればよいかは[キッチンカー出店に必要な書類](/blog/kitchen-car-required-documents)にまとめています。

### 学園祭は別の組み方で

ここまでは毎週の昼食の話です。学園祭のように1日に大勢が集まる行事は、台数や配置の考え方が変わります。行事で呼ぶ場合は[学園祭にキッチンカーを呼ぶ方法](/blog/school-festival-food-truck)をご覧ください。

## よくある質問

### 大学の学食にキッチンカーを呼ぶと、学校に費用はかかりますか？

**持ち出しは0円です。** 募集中の学校31件はすべて売上の歩合で、出店料は出店者が売上から払います。固定額の案件は0件、率は31件中29件が売上の10%でした（2026年9月13日時点）。

### 何曜日の何時に来てもらうのがよいですか？

**週1回・11:00〜14:00から**が組みやすい形です。時刻が書かれた学校の募集6件では、「11:00〜14:00」「12:00〜13:00」のように昼休みを挟んで設定されていました。曜日は「毎週火曜日」から「平日全日（月〜金）」まで幅があります。

### 専門学校でも呼べますか？

**呼べます。** 募集中の学校31件のうち、19件が専門学校・学院です。学食がない、昼休みが短いといった学校ほど、構内に車が来る効果は大きくなります。

### 東京以外の学校でも呼べますか？

**呼べます。** 募集中の学校31件のうち東京都は16件で、残る15件は埼玉・神奈川・茨城・大阪・群馬の学校です。出店者ページでも、埼玉を対応エリアに入れている店が548店、神奈川が545店、大阪が288店あります。

