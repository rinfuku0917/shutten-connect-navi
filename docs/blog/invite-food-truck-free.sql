## 出店料は「主催者が払うお金」ではない

まず、お金の向きを整理します。ここを取り違えると、話が全部ずれます。

キッチンカーの募集でいう**出店料は、出店者が場所側に払うお金**です。主催者が出店者に払う出演料ではありません。2026年9月6日時点で募集中の110件は、すべてこの出店料の形で条件が設定されています。

形は3つ、それに「応相談」を加えた4通りに分かれます。

| 出店料の形 | 件数 | お金の流れ |
|---|---|---|
| 固定のみ | 52件 | 出店者 → 主催者に決まった額 |
| **歩合のみ** | **43件** | **出店者 → 主催者に売上の一定割合** |
| 固定と歩合の併用 | 9件 | 上の2つを足した形 |
| 応相談 | 6件 | 話し合いで決める |

金額まで掲載しているのは**104件**です（2026年9月6日時点）。

### 固定のみ（52件）——金額を決めて受け取る

1日いくら、と決める形です。出店者は売れても売れなくても同じ額を払います。

**ここに出ている金額は、出店者の側が負担する総額です。** 仲介が入るときは手数料が差し引かれるため、募集要項の数字をそのまま受取額として見積もると、実際とは大きく離れます。

金額の水準は、**常設で固定額を出している48件の中央値が平日・週末とも5,000円**でした（2026年9月6日時点）。曜日で分けるかどうかも含めた決め方は[キッチンカーの呼び方](/blog/how-to-call-food-truck)にまとめています。

### 歩合のみ（43件）——現金を1円も出さない

**「無料で呼びたい」に直接あてはまるのがこれです。**

出店者は売上の一定割合を払います。売れなければ払う額も小さくなり、主催者は最初から最後まで1円も出しません。契約時に用意する現金が発生しないので、予算のない催しでも募集を出せます。

**歩合の率も、出店者が支払う側の条件です。** 固定と同じく、仲介を通す場合、主催者が受け取るのはここから手数料を引いた額になります。

### 固定と歩合の併用（9件）

1日の固定額に、売上の歩合を足す形です。9件のうち8件が商業施設に集まっています。来客が日によって大きく振れる場所で、下限を確保しつつ売れた分を分ける設計です。詳しくは[商業施設でキッチンカーの催事を組むには](/blog/mall-food-truck-event)にまとめました。

残る6件は「応相談」——条件を決めきらずに募集を出す形です。初めて呼ぶ場合、これも選べます。

## 【実データ】歩合の率は10％が最も多い

2026年9月6日時点で募集中の110件のうち、歩合が含まれるのは**52件**（歩合のみ43件＋併用9件）。率の内訳はこうなっています。

| 歩合の率 | 件数 |
|---|---|
| **10％** | **35件** |
| 15％ | 13件 |
| 20％ | 4件 |

**10％が35件で最も多く、20％は4件しかありません。**

はじめて募集を出すなら、**10％から**が無難です。率を上げれば場所側の取り分は増えますが、出店者から見れば手取りが減ります。**来てもらえなければ受け取りは0円**なので、高い率を設定して応募が来ないほうが損です。

もうひとつ決めておきたいのが**税の扱い**です。率を売上の税込額にかけるのか、税抜額にかけるのか。2026年9月6日時点で募集中の110件のうち、出店料の文中で税に触れているのは**71件**でした。書かれていないと、精算のときに食い違います。

金額の決め方そのものは[キッチンカーの出店料の相場](/blog/food-truck-fee-guide)に詳しく書いています。

## 学校は31件のうち30件が歩合

「予算を持たない主催者」の代表例が学校です。2026年9月6日時点で募集中の学校の案件は**31件**、そのうち**30件が歩合のみ**でした。残る1件がどの形なのかは集計していません。

なぜ学校で歩合が成り立つのか。以下は**データではなく、条件の設計としての説明**です。

学校には**飲食の出店に使える費目がありません。** 学食の運営費や行事の予算はあっても、「キッチンカーを呼ぶ費用」という項目は普通ありません。固定額を約束するには裏づけになる予算が要りますが、歩合なら払うのは出店者の側です。

出店者の側から見ると、学校は**売上が読みやすい場所ではありません。** 在籍する人数は決まっていても、長期休みや試験期間で客足は大きく振れます。振れる場所で固定額を先に約束するのは重い条件で、**歩合はその振れを両者で分け合う形**です。

30件は、**予算がない事情と、売上が振れる事情が同じ答えに行き着いた**結果と読めます。同じ組み方は自治会や社内イベントでも使えます。

なお、31件は募集の数であって、学校の数とは限りません。同じ学校が複数の枠で募集を出していることがあります。

場所の種類による偏りは、その業態の必然とは限りません。**同じ系列の店舗がまとめて同じ条件を出している**ことによる部分があります。内訳は[スーパーの駐車場にキッチンカーを誘致するには](/blog/supermarket-food-truck)に。

## 0円で呼べない場合もある

ここは正直に書きます。**歩合にしておけば必ず来てくれる、ということはありません。** 以下は**データではなく、条件の設計としての説明**です。

歩合は「売れたら払う」形なので、主催者は損をしません。ですが**出店者は違います。** 車を動かし、食材を仕入れ、人を出して、売れなければ丸ごと赤字です。次の3つが説明できない募集は、歩合でも応募が集まりにくくなります。

### 人通りが読めない

いちばん大きいのがここです。**何人来るのか分からない募集は、出店者に判断のしようがありません。** 条件の良し悪し以前に、比べる材料がない状態です。読める形にするのは難しくありません。すでに手元にある数字を、そのまま出せば足ります。

- 施設なら**1日の来客数**、オフィスなら**その建物の勤務人数**
- 学校なら**在籍数と、昼休みの時間**
- イベントなら**前回の来場者数**。初開催なら「初開催」と書く

数え方を添えた数字がひとつあれば、出店者は自分の客単価から売上を見積もれます。**当てにいく必要はありません。**

2026年9月6日時点で募集中の110件は**常設97件・単発イベント13件**。単発は前回の実績がないことも多いので、そのぶん来場の根拠をていねいに書いてください。呼び方の全体像は[キッチンカーの呼び方](/blog/how-to-call-food-truck)に。

### 電源が無い

キッチンカーは調理に電気を使います。発電機を積んだ車もありますが、燃料代と騒音があり、住宅が近い場所では使えません。

**使える電源があるなら、容量まで書いてください。** 無い場合も、そう書いてあれば発電機を積んだ車が手を挙げられます。書かれていないときだけ、判断のしようがなくなります。

### 搬入ができない

車が入れなければ、どれだけ人が集まる場所でも出店できません。前面道路の幅、ゲートの高さ制限、区画に横付けできるか。キッチンカーの車体は、**普通車の感覚では収まりません。**

**会場を決める前に、実際に車が入って停められるかを確認してください。** 依頼が止まりやすい条件は[キッチンカーの出店依頼はどう出す？](/blog/request-food-truck)にもまとめました。

この3つが説明できないときは、出店料の条件をゆるめる（歩合の率を下げる、応相談にする）か、会場の条件そのものを見直すかになります。**それでも人が集まりにくい催しでは、主催者側が負担する形もあります。** 来場者に無料で配る場合の商品買取、来場が読めない場合の売上保証がこれにあたります（[キッチンカーを呼ぶ費用](/vendor/cost)）。

## 0円で呼ぶために募集に書くこと

主催者が現金を出さない代わりに、**情報を出す**必要があります。募集要項に入れておきたいのは次の項目です。

- **想定の来場者数**と、その数え方
- **場所の性質**——毎週入ってほしいのか、その日だけなのか
- **時間帯**と、**電源・搬入経路・区画の大きさ**
- **出店料の形と率**、そして**税込か税抜か**
- **競合**——同じ敷地に食堂や飲食テナントがあるか

館内で同じものが買えると、出店者の売上は落ちます。**店内や館内に無いジャンル**を選んでください。

選べる相手の数は足りています。2026年9月6日時点で**公開中の出店者は1,386店舗**。対応エリアやジャンルの内訳は[キッチンカーの出店依頼はどう出す？](/blog/request-food-truck)に、実際の車は[登録キッチンカーを見る](/sellers)で見られます。

## よくある質問

### キッチンカーは本当に無料で呼べますか？

