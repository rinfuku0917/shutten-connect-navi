## 出店依頼で伝える7項目

出店コネクトナビの募集フォームの項目に沿って整理すると、こうなります。

| 項目 | フォームの表示 | 書かないとどうなるか |
|---|---|---|
| **日程** | 必須の表示あり | 予定が押さえられない |
| **場所（住所）** | 必須の表示あり | 通える距離か判断できない |
| **電源** | 必須の表示あり（有り／無し） | 有りとだけでは、停める区画まで届くか分からない |
| **搬入・搬出の時刻** | 必須の表示あり | 当日の段取りが組めない |
| **台数** | 必須の表示あり（募集内容） | 1台あたりの売上が読めない |
| **出店料の形** | **表示なし** | 払う額が分からず見送られる |
| **想定人数** | **表示なし（動員目標）** | 売上が見積もれない |

先に断っておきます。フォームには「必須」の印が付きますが、**入力を実際に止めるのはイベント・施設名と都道府県の2つだけ**です。印が付いた項目も、空欄のまま公開できてしまいます。

**問題は下の2つです。** 印すら付かないうえ、出店者がいちばん知りたいところ。ここが空欄だと、比べる材料の無い依頼になります。

このほか、**屋内か屋外か・高さ制限・ゴミの処理・雨天時の対応・車両の留め置き**にも「必須」の印が付いています。印に頼らず、自分で確かめて埋めてください。

### 電源は「有り／無し」だけでは足りない

電源は有り／無しから選ぶ形なので、どちらかは必ず載ります。足りないのはその先です。

有りと答えたなら、**どこから取れるか・どのくらいの容量まで使えるか**を書いてください。広い駐車場では、電源の位置と車両を停める区画が離れていて、コードが届かないことがあります。

無しなら無しで構いません。**発電機を積んだ車を探す**進め方になるだけです。困るのは、有りとだけ書かれていて、位置も容量も分からないときです。

### 想定人数は、正確さより根拠

当てにいかなくてよいので、**数え方を添えて**書いてください。

- 施設なら**平日の平均入館者数**、スーパーなら**1日のレジ通過数**
- イベントなら**前回の来場者数**（初開催ならそう書く）
- 社内なら**フロアの在籍人数と出社率**

根拠のある人数がひとつあれば、出店者は客単価から売上を出せます。**計算できる依頼は、比べられる依頼です。**

### 雨天時は「その他」の中身まで書く

雨天時の対応は、雨天決行・中止・その他の3つから選びます。「その他」なら、どこまでが小雨でどこからが中止かを備考に書いてください。

分かれ目が書いていないと、当日の朝に電話で決めることになります。中止のときに出店料をどう扱うかも、先に決めておくと後で揉めません。

