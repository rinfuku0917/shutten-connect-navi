## 出店料は、形を決めてから出す

依頼の条件でいちばん詰まるのが金額です。出店料の形は**固定のみ・歩合のみ・併用・応相談**の4通りで、募集中110件でいちばん多いのは**固定のみの52件**、常設で固定額を出している48件の**中央値は平日・週末とも5,000円**でした（2026年9月6日時点）。**いずれも出店者の側が負担する総額**で、場所側の受取額ではありません。

どの形にするかは、持ち出しを避けたいのか、金額を先に決めたいのかで変わります。形ごとの内訳と歩合の率は[キッチンカーを無料で呼ぶには](/blog/invite-food-truck-free)に、相場の全体像は[キッチンカーの出店料の相場](/blog/food-truck-fee-guide)にまとめています。

場所の種類によっても相場は動きます。[商業施設の催事](/blog/mall-food-truck-event)と[スーパーの駐車場](/blog/supermarket-food-truck)が参考になります。

書くときは**税込か税別かを必ず添えてください。** 明記しているのは**71件**です（2026年9月6日時点）。精算で食い違うと、次がありません。また、来場者が自分で買う形なら主催者の持ち出しは出ませんが、無料で配る形や売上保証を付ける形では費用が出ます。目安は[キッチンカーを呼ぶ費用](/vendor/cost)に。

## 依頼が止まるのはどういうときか

ここからは**データではなく、条件の設計としての説明**です。応募の数を集計したものではありません。

条件が悪くて断られるほかに、**良し悪し以前に判断できない**という理由もあります。典型は次の4つです。

### 電源が「有り」としか書かれていない

前に書いたとおり、無いこと自体は困りません。困るのは、**現地に着くまで届くかどうか分からない**依頼です。区画まで何メートルあるのか、いくつまで挿してよいのか。これが分からないと、出店者は当日そこで調理できるかを確かめられません。

### 搬入経路が確保できない

キッチンカーは普通車より背が高く、長い車両です。**立体駐車場の高さ制限、私道の幅、段差**で入れないことがあります。フォームに高さ制限の欄があるのはこのためです。区画を決める前に、通れる幅と高さを確かめてください。

### 想定来場者数が説明できない

出店者は、**当日の食数を決めるために来客の見当が要ります。** 「たくさん来ます」では仕込む量が決まりません。数え方を添えた数字がひとつあれば足ります。

### 日程が固まる前に声だけかける

募集中110件のうち**97件が常設**で、同じ曜日に繰り返し入る形が主流です（2026年9月6日時点）。常設は先の予定として押さえる形になるので、**日程が決まった時点で出す**ほうが、相手も予定に組み込みやすくなります。イベントの段取りは[イベントにキッチンカーを呼ぶには](/blog/how-to-invite-kitchen-car)と[イベント・マルシェ・お祭り](/vendor/event)にまとめました。

## よくある質問

### キッチンカーに出店依頼を出すには何を伝えればいいですか？

**日程・場所・電源・搬入と搬出の時刻・台数・出店料の形・想定人数**の7つです。募集フォームでは前の5つに「必須」の印が付きますが、**入力を実際に止めるのはイベント・施設名と都道府県だけ**で、印が付いた項目も空欄のまま公開できます。**出店料と想定人数には印すら付きません。** 屋内か屋外か、高さ制限、雨天時の対応も忘れずに。

### 依頼できるキッチンカーは何店ありますか？

2026年9月6日時点で、出店者ページが公開されているのは**1,386店舗**です。対応エリアは東京765店・埼玉548店・神奈川545店・千葉468店・大阪288店・茨城277店。ジャンルは食事602店・スイーツ511店・ドリンク477店で、**2つ以上を出せるのが524店舗**あります。1店舗が複数のエリアとジャンルに対応するため、合計は登録数を超えます。

### 依頼する前に、どんな車か確認できますか？

できます。[登録キッチンカーを見る](/sellers)で、写真・ジャンル・メニューと価格・対応エリアが見られます。2026年9月6日時点で、**メニューを載せているのは645店舗、写真は552店舗**（公開中1,386店舗のうち）。登録済みのメニュー**3,685品**は全品に価格が入っているので、客単価の見当をつけてから依頼を出せます。

### 出店料はいくらに設定すればいいですか？

2026年9月6日時点で、常設で固定額を出している48件の**中央値は平日・週末とも5,000円**でした。**これは出店者の側が負担する総額**で、場所側の受取額ではありません。形は固定のみ・歩合のみ・併用・応相談の4通りで、募集中110件のうち固定のみが52件と最も多い形です。内訳は[キッチンカーを無料で呼ぶには](/blog/invite-food-truck-free)に。**税込か税別かは必ず書いてください。**

### どのくらい前に依頼を出せばいいですか？

日程が決まった時点です。2026年9月6日時点で、募集中110件のうち**97件が常設**で、同じ曜日に繰り返し入る形が主流です。早く出しておくほど、相手も予定に組み込みやすくなります。

### 電源や水道が無い場所でも依頼できますか？

できる場合があります。**発電機や給排水タンクを備えた車両**なら、設備の無い会場でも出店できます。備えているかどうかは車ごとに違い、探す条件がひとつ増えるので、**「無し」と正しく書いておく**ことが前提になります。

