## 私有地で売るのに要るのは「承諾」と「営業許可」

公園や道路で売るときは、役所の許可が絡みます。私有地では、その代わりに**土地の持ち主の側の承諾**が必要になります。役所に出す書類が減るぶん、「誰に聞けばよいか」を自分で見きわめなければなりません。

### 承諾をくれる人は、本当にその土地を貸せる人か

同じ駐車場でも、「いいよ」と言える立場の人は限られています。

| 声をかけた相手 | その承諾で足りるか | 確かめること |
|---|---|---|
| 土地の所有者 | 足りる | 名義が本人か（相続・共有のこともある） |
| 管理会社・本部の担当部署 | 任されている範囲なら足りる | 飲食販売まで任されているか |
| 店長・支配人 | 決められないことが多い | 本部の了解を取ってもらえるか |
| テナント・駐車場の借り手 | それだけでは足りないことがある | 貸主が又貸しを認めているか |

とくに注意したいのは下の2行です。店舗が土地や建物を借りている場合、**駐車場を第三者に使わせるには貸主の承諾が要ることがあります。** 借りている側だけの「いいよ」で始めると、あとで貸主から止められて、出店が続けられなくなります。

貸す側がどんな手続きや確認をしているかは、[駐車場をキッチンカーに貸すには](/blog/renting-parking-space)に書きました。相手が何を気にしているかを知っておくと、話が早く進みます。

### 営業許可は、私有地でも必要

土地の承諾が取れても、**保健所の営業許可が無ければ売れません。** 公園か私有地かに関係なく、飲食を売る以上は要ります。

見落としやすいのは管轄です。営業許可が有効なのは許可を出した自治体の区域内なので、**県境を越えた先の駐車場で売るなら、出店先の許可が要ります。** 詳しくは[キッチンカーの出店に必要な書類](/blog/kitchen-car-required-documents)を見てください。

### 敷地からはみ出すと、話が変わる

車も列も敷地の中に収まっていれば、道路の許可は関係しません。ところが、**お客さんの列や看板、のぼりが歩道にはみ出すと、そこは道路の扱いになります。** 道路で物を置いたり人を並ばせたりするには、警察署や道路の管理者の許可が関わります。

用途地域や自治体の条例による制限、消防への届出が要るかどうかは**地域によって違います。** 火を使うメニューなら、出店先を管轄する消防署に聞いておくと確実です。

## 【実データ】常設の出店場所は、ほぼすべて土地を管理する側が出した募集

出店コネクトナビに掲載している**公開中の289件**のうち、常設（決まった曜日に続けて出る募集）は**192件**です。会場の種類で分けると、次のとおりでした（1件に複数の種類が付くため、合計は192件を超えます）。

| 会場の種類 | 常設192件のうち |
|---|---|
| 大学・学校 | 97件 |
| スーパーマーケット | 42件 |
| イベント会場 | 31件 |
| 商業施設 | 26件 |
| オフィス街 | 5件 |
| 公園・広場 | 2件（2件ともゴルフ施設） |
| 種類の記入なし | 20件 |

「公園・広場」に入っている2件も、中身はゴルフ施設です。続けて出られる場所は、**学校・店舗・企業など、その土地を管理している側が自分で出している募集**だということです。募集を出している側が、すでに土地を使わせる判断を済ませているので、承諾の相手を探す手間はかかりません。

ただし、この中には私有地でない場所もあります。常設の学校のうち少なくとも12件は、県立・都立・公立の学校です。公立の学校の敷地は公有地なので、使わせるかどうかを決めるのは、学校とそれを設置する役所の側です。手続きの性格は私有地と違いますが、募集に応募する出店者から見れば、承諾を取るのは募集を出した側という点は同じです。

### 茨城県は、スーパーの店前・駐車スペースの募集が中心

案件名か説明文に「駐車場」「駐車スペース」とはっきり書いた案件は**289件中6件**（うち募集中4件）です。これより広く「駐車」の語で探すと、茨城県の募集中17件のうち**13件**に当たります。13件とも、同じスーパー1社の店舗の募集です。

つまり、茨城県で駐車場の募集が多く見えるのは、1つの系列が店舗ごとに募集を出しているためです。県全体の傾向というより、**その系列の店舗を回る形が組みやすい県**と考えるほうが正確です。[茨城県の出店場所の一覧](/places/area/ibaraki)で中身を見られます。

スーパーの駐車場を貸す側がどう条件を決めているかは、[スーパーの駐車場にキッチンカーを誘致するには](/blog/supermarket-food-truck)にまとめています。

### 「何か月先まで申し込めるか」も、土地を持つ側が決めている

出店コネクトナビでは、施設によって**申し込める先の日付に上限**を設けています。上限を設けている施設は、いまはどれも4か月先までです。施設側が答えられない遠い日付で申し込まれると、出店者を待たせたままになるため、申し込みの入口で止めています。

私有地では、いつ・どこを使わせるかは土地を管理する側の都合で決まります。自分で交渉するときも、**相手の予定がどこまで決まっているか**を先に聞いておくと、話が宙に浮きません。

## 応募・交渉の前に確かめる4つのこと

承諾の相手がはっきりしたら、次は「その場所で本当に営業できるか」です。出店コネクトナビの設備欄（記入のある140件）から、見ておく項目と、実際にどれくらい条件が割れているかを並べます。

### 1. 電源と給水

**電源ありは123件、なしは17件。給水ありは102件、なしは38件**でした。電源が無ければ発電機、給水が無ければタンクの水だけで営業時間を回すことになります。音やにおいを気にする場所では発電機を嫌がられることもあるので、使えるかどうかまで聞いておきます。

### 2. 区画と車の大きさ

**駐車可は118件、不可は16件**（記入のあった134件のうち）。**高さ制限がある案件も7件**ありました。立体駐車場や屋根の下の区画では、車高を測って伝えておきます。

### 3. 出せる形

**キッチンカーのみが122件、キッチンカーかテントを選べるのが18件**です。テントで出るつもりなら、ほとんどの場所では出られないと考えておいたほうが安全です。

### 4. 出店実績を問われるか

**出店実績を問う案件は140件中32件**でした。募集中だけに絞ると**83件中29件**と、割合が上がります。私有地の管理者は、自分の敷地で事故やトラブルが起きるのを避けたいので、経験のある車を選びがちです。

初めての出店なら、実績を問わない募集から入り、出店の記録を積んでから条件の厳しい場所へ広げるのが順当です。

## 自分で土地の持ち主に持ちかけるとき

募集が出ていない場所に自分で話を持ちかける方法もあります。進め方の全体は[キッチンカーの出店場所の探し方](/blog/kitchen-car-location-guide)の「方法2」にあります。ここでは、私有地ならではの注意点だけ足します。

- **承諾は書面でもらう。** 使ってよい区画・曜日・時間を書いてもらうと、担当者が替わっても話が続く
- **承諾の範囲を越えない。** 認められた区画の外に客席やのぼりを広げると、それだけで打ち切りの理由になる
- **貸主の承諾が要る土地か聞く。** 相手が土地を借りている側なら、その先の貸主の了解まで取れているかを尋ねる

出店コネクトナビでは、出店者の**運転免許証（表裏）・食品衛生責任者証・営業許可証・損害賠償保険証書・PL保険証券の6種類を必須**として、1件ずつ確認しています。営業許可証と2つの保険の証券は、自分で交渉するときも土地の持ち主にそのまま見せる資料になります。このサイトに出すものと同じなので、先に1式そろえておくと二度手間になりません。

## よくある質問

### 知人の土地なら、承諾だけで売ってもいいですか？

承諾だけでは足りません。**営業許可は、私有地でも必要です。** また、知人がその土地の所有者本人か、借りているだけなのかも聞いておきます。借りている土地なら、貸主の承諾も要ることがあります。

### 承諾の書面には、何を書いてもらえばよいですか？

少なくとも、使ってよい区画、曜日と時間、期間、使用料の有無と額、連絡先の5つです。火を使うか、発電機を回すかも書き添えておくと、あとで「聞いていない」と言われにくくなります。決まった書式はないので、双方が同じものを1部ずつ持っておきます。

### 自分が借りている月極駐車場で、売ってもいいですか？

月極駐車場の契約は、車を停めるためのものであることが一般的です。そこで物を売るのは契約の範囲を越えることが多いので、管理会社か貸主に、販売に使ってよいかを先に尋ねます。了解が出たら、その内容も書面でもらっておきます。

