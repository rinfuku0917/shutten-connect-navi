### 会期は6日間。うち4日が平日

会期は2025年12月20日（土）から25日（木）までの6日間でした。土日は最初の2日だけで、**22日から25日までの4日間は平日**です。クリスマスの催しは「12月25日に向かって続くもの」なので、週末だけで区切れません。

平日に常設の出店先を持っている人は、その曜日と重なります。応募する前に、平日の4日間に車と人を回せるか、常設の先を休めるかを決めておきます。

### 設備と条件は要項にこう書かれていた

