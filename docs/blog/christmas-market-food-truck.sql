### 提供時間：日が短い

東京の12月は、16時半ごろに日が沈みます。冬に隅田公園で開かれたご当地鍋の催しの営業時間は10時〜18時でした。こうした会期では、**営業時間の後半は暗い中での営業**になります。手元の照明、メニュー表を照らす明かり、足元の安全を用意しておきます。

撤収の時刻も要項で見ておきます。暗く寒い中での片付けは時間がかかるので、会場を出る時刻から逆算して閉店の準備を始めます。

### 売れるもの：催しのテーマに合わせる

先に断っておくと、出店コネクトナビは冬の催しで何が売れたかのデータを持っていません。そのため、「このメニューが売れる」とは書けません。

手がかりになるのは、**催しの名前と主催者のテーマ**です。冬の催しの案件にも「鍋グランプリ」「地酒＆地肴」のように、テーマをはっきり出したものがあります。テーマのある催しでは、主催者は**そのテーマに合う店**を選びます。応募のときは、自分のメニューのうちテーマに合うものを前に出して伝えます。

## 冬の催しに応募する前の段取り

冬の催しは、夏と同じ持ち物では足りません。応募の前に、次の4つを自分の側で決めておきます。

- **電気の使い道の一覧。** 保温機器・照明・レジを並べ、会場の電源で足りるか、発電機を足すかを決める
- **水の量。** 給水が無い会場なら、提供する食数と湯を沸かす分から逆算して積む量を決める
- **暗くなってからの明かり。** 手元・メニュー表・足元の3か所
- **撤収の時刻と、ごみの積み場所。** 会期が続くなら毎晩の片付けの時間も見込む

書類の準備も、この時期に済ませておきます。応募は会員登録の時点でできます。ただ、選ばれるには書類が要るので、**募集が出る前の秋のうちにそろえておきます。** 何を出せばよいかは[キッチンカーの出店に必要な書類](/blog/kitchen-car-required-documents)を、出店者ページの写真やメニューの埋め方は[出店依頼をもらうための準備](/blog/get-food-truck-offers)を見てください。

### 来年のために、天候と来客数を残す

出店コネクトナビでは、出店した日ごとに売上を報告し、そのとき天候・来客数・品目ごとの販売食数も入れます。

冬の催しは、天気と気温で客足が大きく変わります。その日に何人来て何が何食出たかを毎日残しておけば、**翌年のクリスマスに応募するかどうか、何をどれだけ仕込むか**を自分のデータで決められます。

## よくある質問

### クリスマスの出店募集は、毎年いつごろ出ますか？

このサイトの実例では、2025年12月20日に始まったクリスマスフードフェスタが9月4日に掲載され、開催の107日前でした。イベントの募集は4月と8月に多く、11月・12月に掲載されたものは97件中4件です。9月から[出店場所の一覧](/places)を見ておくと、取りこぼしにくくなります。

### 会期の途中の日だけ出ることはできますか？

案件によります。クリスマスの実例の要項には、途中の日だけの参加についての記載はありませんでした。書かれていない場合は、出られない日を先に主催者へ伝え、それでも応募してよいかを尋ねます。平日を含む長い会期ほど、この相談は早めにしておきます。

### 電源がある会場なら、発電機は持っていかなくてよいですか？

使いたい機器の合計が、会場の電源の容量に収まるなら要りません。ただ、容量は要項に書かれていないことが多く、冬は保温と照明で使う量が増えます。機器の一覧を主催者に見せて足りるかを尋ね、足りなければ発電機を足します。

