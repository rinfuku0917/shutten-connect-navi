## 企業の募集に応募する前に聞いておくこと

募集要項に書かれていないことが多い項目です。応募の前か、決まった直後に担当者へ聞いておきます。

1. **休憩の時間と分かれ方。** 一斉か、交代か。販売を始める時刻の目安になります
2. **発電機と排水。** 電源・水が無い区画なら、発電機を回してよいか、排水をどう持ち帰るか
3. **メニューの指定。** 敷地内の催しでは、品目を決めて募集していることがあります
4. **支払いの形。** 社員が1食ずつ払うのか、会社がまとめて払うのか

4つ目は見落とされがちです。会社がまとめて払う形では、登録番号の入った請求書を求められることがあるので、自分がインボイスに登録しているかを先に伝えておきます。

入構の手続きや構内のルールを企業の側がどう決めているかは、募集する側に向けて書いた[社食の代わりにキッチンカーを福利厚生に](/blog/office-welfare-food-truck)が参考になります。守衛での受付や車両の高さなど、企業が気にする点を先に知っておくと、打ち合わせが短く済みます。

## 出店したあと、次につなげる記録の残し方

企業の案件は、1回目の出来で次の曜日が増えるかどうかが決まりやすい場所です。出店コネクトナビでは、出店日ごとに次のことを出店者に報告してもらっています。

- 売上と、品目ごとの販売食数
- 天候と来客数
- 所感

報告した数字は、施設へ出す開催日ごとの報告書にも載ります。企業の担当者は、社員が何人来て何食売れたかを、出店日ごとに同じ形で見られます。次の曜日を増やしてもらう話も、この数字があれば進めやすくなります。

