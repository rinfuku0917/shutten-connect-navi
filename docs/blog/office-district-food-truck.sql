## 「オフィス街に出る」には3つの形がある

オフィスで売ると一口に言っても、誰の土地で売るかで、話を通す相手がまったく変わります。

### 企業の敷地の中で、社員に売る

工場・研究所・本社の構内に区画を借りて、社員に昼食を売る形です。話を通す相手はその会社で、募集もその会社が出します。このサイトに出てくるオフィスの案件は、ほぼすべてこの形です。

### オフィスビル前の広場で売る

ビルの前の広場や公開空地も、道路ではなく**誰かの土地**です。売るには土地の所有者か管理者の承諾が要ります。使ってよい場所・時間・台数はビルごとの決まりで違うので、管理者に直接聞くのが確実です。

### 路上・歩道で売る

道路で売る場合は、警察と道路管理者の許可が関わり、移動販売を認めるかどうか自体が地域で違います。「この通りなら売れる」と一般論では言えないため、この記事では扱いません。

どの形でも、**保健所の営業許可は別に要ります。** 土地の承諾が取れても、出店先を管轄する自治体の営業許可が無ければ売れません。この点は[キッチンカー出店に必要な書類](/blog/kitchen-car-required-documents)で詳しく扱っています。

## 【実データ】企業の募集8件は、社員ランチと敷地内の催しが半々

### 8件の内訳

案件名に社名が入り、会場がその会社の拠点になっている募集を数えると、**公開289件のうち8件**でした。

| 切り口 | 企業の募集8件のうち |
|---|---|
| 募集中 | 4件 |
| 神奈川県 | 7件 |
| 東京都 | 1件（品川区） |
| 昼の社員ランチ | 4件 |
| 敷地内の催し（社内のお祭り・家族を招く行事・車のフェア） | 4件 |

神奈川が多いのは、相模原市・厚木市・茅ヶ崎市・横浜市などにある企業の拠点から募集が出ているためです。催しの4件には、同じ11月の家族見学会を、別々の募集として2件に分けて出したものが含まれます。

「オフィス街」の区分が付いた案件は、289件のうち5件です。ただしそのうち江東区の1件は、区分こそオフィス街ですが、会場はゴルフ施設の前で**出店日は土日祝**でした。区分の名前だけで平日の昼の案件だと決めつけず、日程の欄まで読んでから応募を考えてください。

### 敷地内の催しは、メニューの指定がある

催しの募集は、昼休みの販売とは中身が違います。ある社内のお祭りは**10時から15時まで、来場見込み700〜1,000名**で、提供してほしいのは「スイーツ・ドリンク」、それ以外のメニューとお酒は遠慮してほしいと書いていました。家族を招く行事の募集には「ご飯ものとデザート系の2台」「参加者は300名程度」とありました。

つまり企業の催しでは、**何を売るかを企業の側が先に決めている**ことがあります。自分のメニューが指定に合うかを、応募の前に要項で見ておきます。合わない品目を持ち込むと、当日になって売れないことがあります。

### 掲載は、開催の2か月以上前

11月に開かれる2つの催し（社内のお祭りと、家族を招く行事）の募集は、それぞれ開催の**62日前と116日前**にこのサイトへ掲載されていました（掲載日は最後に公開された日）。秋の社内行事なら、夏の終わりには募集が出ています。

### 電源も水も無い前提で考える

8件のうち、設備欄に記入があるのは3件で、**3件とも電源なし・給水なし**でした。

サイト全体と比べると差がはっきりします。設備欄のある140件では、電源ありが123件、給水ありが102件です。**企業の敷地は、設備の無い区画を貸す形が中心**だと考えておくほうが安全です。

発電機を回すなら、音と排気がどこへ流れるかも問題になります。事務所の窓や休憩所の近くに区画があるときは、応募の前に発電機を使ってよいかを聞いておきます。

### 出店実績を問う案件が多い

同じ3件のうち**2件が「出店実績を問う」**としていました。設備欄のある140件全体では、実績を問うのは32件で、108件は問いません。

社外の車を構内に入れる以上、企業は慎重になりがちです。実績の無いうちは、**書類をそろえて信用を示す**のが近道です。

## 学校の学内ランチとの違いは、休憩の分かれ方

