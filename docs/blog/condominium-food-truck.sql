ジャンルは**食事603店・スイーツ512店・ドリンク478店**。2つ以上のジャンルを持つ店が525店あります。

マンションの敷地には、競合する売り場がありません。**平日の夕方は食事、週末の昼はスイーツとドリンク**、行事の日は3つを組み合わせる、と時間帯で選べます。

登録されているメニューは**3,695件で、すべてに価格が入っています**。写真つきは2,834件です。どの車が何をいくらで売るのかを告知の前に確かめられるので、住民への案内に価格まで書けます。

## 曜日を決めて続ける

出店コネクトナビで募集中の110件のうち、**99件が常設**です（こちらも全体の数字）。条件が決まった場所は、続ける形が主流です。

マンションも同じです。「毎週水曜の夕方」のように決めれば、住民がその日を予定に入れて待つようになります。平日の夕方は夕食の支度を省きたい世帯が、週末の昼は家族連れが買いに来ます。**まず1つの曜日に絞って始め、売れ行きを見て増やす**のが続けるこつです。

## 始める順番

1. 管理会社に相談し、規約と使える場所を確認する
2. 場所・曜日・時間帯・出店料の形を決める
3. 理事会で試行を承認し、続けるなら総会に諮る
4. 住民に告知する
5. 募集を出し、応募してきた出店者から選ぶ
6. 初回は立ち会い、3か月をめどに条件を見直す

出店者に出してもらう書類は[キッチンカーの出店に必要な書類](/blog/kitchen-car-required-documents)で、呼ぶまでの流れの全体は[キッチンカーの呼び方](/blog/how-to-call-food-truck)で確認できます。

## よくある質問

### 管理組合がお金を出す必要はありますか？

ありません。出店料は、固定でも歩合でも出店者が場所側に払うお金です。持ち出し0円で始められます。

### 総会の決議は必要ですか？

行事で1回呼ぶだけなら、理事会の承認で進められることが多いです。継続して共用部を使わせるなら総会に諮るのが確実で、規約を変える場合は特別決議になります。

### 賃貸の団地の自治会でも呼べますか？

呼べます。自治会で話をまとめ、敷地の所有者（管理者）の許可を取ってから進めてください。

### 騒音やにおいの苦情が心配です

電源の貸し出しか低騒音型の発電機、住戸から離した配置、時間帯の絞り込みで防げます。苦情の窓口を一本化しておくと、対応も早くなります。

