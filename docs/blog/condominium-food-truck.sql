## キッチンカーはマンションに足りないものを埋める

### 買い物の不便がひとつ消える

食事のほうが敷地の中まで来るので、坂道もバスも要りません。高齢の世帯には夕食の一品に、共働きの子育て世帯には帰宅後の一食になります。**玄関を出てすぐ温かい食事が買える**のは、どの住民にも伝わる便利さです。

### 共用部が「使われる場所」になる

平日の来客用駐車場、行事のない広場、エントランス前のロータリー。管理費で維持しているのに使われていない場所が、週に一度にぎわう場所に変わります。

### 住民どうしの顔が見える

行列に並べば、同じ棟の人と自然に言葉を交わします。夏祭りや防災訓練に合わせて呼べば、**行事に人を集める目玉**になります。

## 管理組合で決めることは4つ

### 1. 共用部の使用許可と規約の確認

駐車場・広場・通路は共用部分で、使い方は管理規約と使用細則で決まっています。外部の事業者が営業に使うことを想定していない規約は多いので、まずここを確かめます。

- 行事での1回限りの出店は、理事会の承認で進められることが多い
- 毎週のように続けるなら、総会に諮って決議を取るのが確実
- 規約そのものを変える場合は、総会の特別決議が要る

規約の読み方と議案書の形は、管理会社に相談すれば整えてもらえます。**賃貸の団地では、敷地を管理しているのは自治会ではなく所有者**です。自治会で話をまとめたうえで、管理者の許可を取ってください。

外部の事業者に場所を使わせて出店料を受け取る場合は、税の申告の扱いも管理会社か税理士に一度確認しておきます。

### 2. 音とにおい

マンションで最初に出る心配がこれです。先に手を打てば防げます。

- 発電機の音：共用の電源を貸せるなら貸す。貸せないなら低騒音型を条件にする
- 調理のにおい：住戸の窓やバルコニーの真下を避け、棟から離れた位置に停める
- 時間帯：早朝と夜遅くを避け、夕食の買い物に合う時間に絞る

### 3. 駐車スペースと動線

キッチンカー1台の区画と、並ぶ人が立つ場所をセットで確保します。

- 来客用駐車場を使うなら、その時間帯の予約を止めておく
- **消防車の進入路や、はしご車の活動用の空地には停めない**
- 住民の車の出入り、ゴミ収集車、駐輪場とエントランスの出入りをふさがない
- 敷地の入口の高さ制限と、スロープを車両が通れるかを確認する

区画の貸し方、契約書に入れる項目、保険の確認は[駐車場をキッチンカーに貸すには](/blog/renting-parking-space)に、敷地の外の空き地や駐車場を使う組み方は[遊休スペースの活用にキッチンカー誘致という選択肢](/blog/vacant-space-food-truck)にまとめています。

### 4. 住民への告知

告知の出来が、初回の売れ行きを決めます。掲示板、全戸配布、管理アプリで次の内容を知らせてください。

- 日時と場所、雨の日の扱い
- 来るお店と、**メニューと価格**
- 意見や苦情の窓口（管理組合か管理会社に一本化する）

「まず3か月の試行」と書いておくと、慎重な住民の理解も得やすくなります。

## 【実データ】出店料は出店者が払う。管理組合の持ち出しは0円

出店料は、**出店者が場所側に払うお金**です。管理組合が出店者に払うものではありません。

出店コネクトナビで募集中の案件110件の出店料の形は、次のとおりです。**マンションに限った数字ではなく、スーパー・学校・商業施設などを含む全体の数字**です。

| 出店料の形 | 内容 | 件数 |
|---|---|---|
| 固定のみ | 1日あたり決まった額 | 52件 |
| **歩合のみ** | 売上に対する割合 | **43件** |
| 併用 | 固定＋歩合 | 9件 |
| 応相談 | 話し合いで決める | 6件 |

率は、歩合が含まれる52件のうち**35件が売上の10%**で、最も多い設定です（15%が13件、20%が4件）。

マンションで始めるなら、**歩合が向きます。** 世帯数は分かっても、何人が買いに来るかは開けてみるまで読めません。歩合なら売れなかった日の出店者の負担が軽く、**続けて来てもらえます**。管理組合は1円も出さず、売れた分の一部を受け取る側に回ります。

ここでいう出店料は、固定でも歩合でも**出店者が払う総額**です。仲介を通す場合、管理組合の受取は手数料を引いた額になります。固定額の相場は[キッチンカーの出店料の相場](/blog/food-truck-fee-guide)に、持ち出し0円で呼べる仕組みは[キッチンカーを無料で呼ぶには](/blog/invite-food-truck-free)にまとめました。

夏祭りで**住民に無料で配りたい**場合は、管理組合が食数ぶんを買い取る形になります。費用の決まり方は[キッチンカーを呼ぶ費用と料金相場](/vendor/cost)をご覧ください。

