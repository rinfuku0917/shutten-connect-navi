### 常設の募集に、公園は1件もない

出店形態で分けると、**12件はすべてイベント型**です。公開案件のうち常設（決まった曜日に続けて出る募集）は192件ありますが、その中に公園・緑地の案件は**0件**でした。常設の出店先は、学校・スーパー・商業施設・企業の敷地など、**その土地を管理している側が自分で出す募集**がほとんどです。

### 募集要項に、公園の許可の話は出てこない

289件の募集要項を探しても、「占用」「使用許可」「道路使用」という言葉を書いた案件は**0件**でした。公園の12件も、出店者に許可の取得を求める書き方はしていません。

このサイトに出てくる公園の出店は、**催しを開く主催者が会場を押さえ、その中の区画を出店者に割り振る形**です。出店者の側に回ってくるのは、公園の手続きではなく、主催者が決めた出店の条件です。主催者が募集の前に何を決めているかは、[自治体・公園の催しにキッチンカーを集める方法](/blog/municipal-event-food-truck)に主催者の目線でまとめています。

