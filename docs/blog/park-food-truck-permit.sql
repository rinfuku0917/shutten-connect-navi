## 公園での販売に関わる2つの許可

### 公園の管理者が出す許可

自治体の都市公園は、都市公園法と、その公園を管理する自治体の条例で運営されています。園内での物品の販売や飲食の提供は、**条例で禁止しているか、許可制にしているのが一般的**です。

許可を出すのは公園の管理者です。多くは市区町村や都道府県の公園担当の部署で、運営を任された指定管理者が窓口になっている公園もあります。国営公園なら国の事務所です。

手続きの名前は一つに決まっていません。行為許可、使用許可、占用許可など、**自治体によって呼び名も中身も違います。** 「公園で売るには〇〇許可」と一語で覚えるより、「その公園の管理者に、販売の許可が要るか聞く」と覚えておくほうが確実です。探し方の全体の中での公園の位置づけは[キッチンカーの出店場所の探し方](/blog/kitchen-car-location-guide)に書きました。

### 保健所の営業許可は、公園の許可とは別

キッチンカーで食べ物を売るには、車ごとに保健所の営業許可が要ります。これは公園の許可とは**まったく別の手続き**です。公園の管理者から販売の許可が出ても、営業許可がなければ売れません。逆に、営業許可を持っていても、公園で売ってよいことにはなりません。

営業許可が効くのは、許可を出した自治体の区域の中だけです。公園のある場所が、手元の許可の区域に入っているかを先に確かめてください。取り方は[キッチンカーの営業許可の取り方](/blog/kitchen-car-business-license)、区域の考え方は[キッチンカーの出店に必要な書類](/blog/kitchen-car-required-documents)で説明しています。

### 自治体ごとに違うので、聞いて確かめること

公園の管理者に問い合わせるときは、次の点を一つずつ聞くと話が早く進みます。

- その公園で、食べ物の販売を認めているか（催しのときだけか、ふだんもか）
- 申請できるのは誰か（個人の出店者か、催しを開く団体か）
- 申請の期限と、手数料がかかるか
- 車を園内に入れてよいか、入れてよい時間帯はいつか
- 火気や発電機の使用に決まりがあるか

ここに挙げた答えは、公園ごとに変わります。**この記事で「どこでも同じ」と言える答えはありません。**

