### 区画の広さと、車の大きさ

兵庫県の舞子公園の催しは、キッチンカーの区画を3m×5m、屋台とブースを3m×3mと分けていました。八王子の駅前のマルシェは、**軽自動車のキッチンカーと普通車のキッチンカーで区分を分けています。** 代々木公園の催しでは、テントとプレハブで区分が分かれていました。

応募の前に、自分の車の全長と、ひさしやのぼりを出したときの幅を測っておくと、区画に収まるかをすぐ答えられます。区画ごとの出店料の実例は、先に挙げた自治体の催しの記事に載せています。

### 全日程に出られるか

複数日の催しでは、**全日程に出られる店を優先する**と書いた要項がありました。八王子のマルシェでは「4日間出店可能な方を優先」「3日間出店出来る方を最優先」と、回ごとに明記しています。1日だけ出たい場合は、応募の前に主催者へ相談してください。

### 出店料の払い方

払い方は催しごとにばらばらでした。

- 当日、会場で現金で払う（大高緑地）
- 出店が決まってから、入金の案内が届く（山田池公園）
- 会場での販売は基本的に電子マネーで、売上から歩合を差し引いた額が**3週間ほど後に振り込まれる**（代々木公園）
- 会場の駐車場を使うかどうかで、出店料の額が分かれる（尼崎城址公園）

電子マネーで売って後から精算する催しでは、**当日の現金が手元に残りません。** 仕入れや燃料の支払いの計画に響くので、精算の時期は必ず確かめておきます。

### 設備は、要項に書かれていないことが多い

12件の公園の案件には、電源・給水・火気の有無を書く欄（設備欄）が**1件も埋まっていませんでした。** 書かれていない以上、電源や水は無いものと考えて、発電機と給排水のタンクを持ち込める状態で応募するのが安全です。発電機を使ってよいか、音の出る機械に決まりがあるかは、公園ごとの決まりによるので主催者に聞いてください。

## 応募の前に確かめる4つ

主催者のいる催しに出るとき、出店者が自分で確かめることは次の4つです。

1. **主催者が公園の許可を取っているか。** 取っていない段階の募集なら、許可が下りなかったときの扱い（中止・返金）を聞いておく
2. **営業許可の区域。** 公園のある場所が、手元の営業許可の区域に入っているか
3. **保険の証券が開催日に有効か。** 損害賠償保険とPL保険の両方があるか
4. **募集が出る時期。** 秋冬の催しを狙うなら、夏から募集を見ておく

4つ目の実例として、冬の代々木公園の催しは開催の91日前、隅田公園の催しは73日前にこのサイトへ掲載されていました。2件とも開催の2か月以上前です。※掲載日は、このサイトに最後に公開された日（日本時間）です。出し直した案件や、以前のサイトから移した案件では、実際の募集開始はもう少し早い場合があります。

出店コネクトナビでは、運転免許証（表・裏）・食品衛生責任者証・損害賠償保険証書・営業許可証・PL保険証券の6種類を必須の書類にしています。公園の催しは募集の数が少なく、出たときに迷わず応募できるよう、6種類は先にそろえておきます。

## よくある質問

### 主催者が公園の許可を取っていれば、保健所の営業許可は要りませんか？

要ります。公園の許可は「その場所で売ってよいか」、営業許可は「その車で食べ物を作って売ってよいか」を決めるもので、役割が違います。催しによっては、主催者が催し全体として保健所に届け出る場合もありますが、それで出店者一人ひとりの営業許可が要らなくなるわけではありません。

### 催しではなく、ふだんの日に1台で公園に出ることはできますか？

公園によります。個人の出店者が単独で申請できる公園もあれば、催しを開く団体にしか許可を出さない公園もあります。このサイトに掲載した公園の12件は、どれも主催者のいる催しで、1台で出る形の募集はありませんでした。単独で出たいなら、その公園の管理者に、個人の申請を受けているかを最初に尋ねます。

### 主催者が「許可は申請中」と書いていたら、応募してよいですか？

応募はできますが、許可が下りなかったときの扱いを先に聞いておきます。催しが中止になった場合に出店料が返ってくるか、いつまでに中止が決まるかの2点です。仕入れや人の手配を始める時期も、その答えに合わせて決めます。

