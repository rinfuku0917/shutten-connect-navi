2週間前というのは、あくまで**相談を受けられる最低ライン**です。募集を出し、応募を待ち、そこから選ぶところまで含めるなら、早く動くほど選べる幅は広がります。イベントで台数を揃える場合は、[イベントにキッチンカーを呼ぶには](/blog/how-to-invite-kitchen-car)にもっと早い目安を書きました。動き出すのは**開催日と場所が決まった時点**で構いません。

## 【実データ】1回だけ呼ぶのか、毎週呼ぶのか

呼び方は**1回だけの単発**と、**毎週または毎月の常設**に分かれます。2026年9月6日時点で募集中の110件を数えると、こうなります。

| 呼び方 | 件数 |
|---|---|
| **常設**（毎週・毎月、決まった曜日） | **97件** |
| 単発のイベント | 13件 |

大半が常設です。募集の主流は「1日かぎりの催し」ではなく、**決まった曜日に繰り返し入ってもらう形**だということになります。

「どこに呼ぶか」という別の軸で分けると、内訳はこうです。

| 場所の種類 | 件数 |
|---|---|
| スーパー | 34件 |
| 学校 | 31件 |
| 商業施設 | 29件 |
| イベント会場 | 7件 |
| オフィス | 5件 |

これは「どこに呼ぶか」で分けた主な内訳（2026年9月6日時点）で、上の常設・単発（いつ呼ぶか）とは軸が違います。**イベント会場の7件と、単発イベントの13件は数え方が別**です。上位のスーパー・学校・商業施設は、いずれも**もともと人が集まっている場所**でした。

### 単発なら、集客はこちら側の仕事になる

ここからはデータではなく、**条件の設計としての説明**です。

単発は、来場者を呼ぶところから主催者の仕事になります。告知の手間も費用もこちら持ちで、天気が外れれば材料が残るのは出店者の側です。前回の実績がない催しほど、当日の売上は見積もりにくくなります。

そこで単発では、**読めない部分を埋める条件**を用意します。想定来場者数とその数え方を正直に伝える、出店料を下げる、売上を保証する。いずれも、読めない部分を主催者側が引き受ける形です。

### 常設なら、決めるのは曜日と回数

常設で決めるのは日付ではなく**曜日**です。「毎週水曜」「第2土曜」という形になり、いったん決めたらしばらく変えない前提で組みます。回数も同時に決めます——毎週なのか、月に1回なのか。

先の出店予定を早くから押さえる出店者にとって、曜日が決まっている募集は**予定に組み込みやすくなります。** 呼ぶ側も、一度決めた条件をそのまま使い続けられます。決めごとが少なくて済むのは、単発よりも常設のほうです。

場所ごとの条件設計は、[商業施設の催事](/blog/mall-food-truck-event)、[スーパーの駐車場](/blog/supermarket-food-truck)、[駐車場を貸す場合](/blog/renting-parking-space)に書いています。

## 【実データ】曜日で金額を変えるのが普通

出店料でよく迷うのが「平日と週末で分けるべきか」です。募集中110件のうち、**両方に金額を出しているのは39件**。その39件を比べると、こうなります。

| 平日と週末の関係 | 件数 |
|---|---|
| **平日のほうが安い** | **25件** |
| 同額 | 14件 |
| 平日のほうが高い | **0件** |

読み方は2つあります。「分ける／分けない」は会場ごとに割れています（25件対14件）。一方で「分けるならどちら向きか」は、**例外なく平日を安くする**方向でした。来客が多い曜日ほど売上が立つので、出店者もその分は払えます。

金額の水準はこうです。2026年9月6日時点で、**常設で固定額を出している48件の中央値は、平日も週末も5,000円**。同じ48件で最も低いのは平日3,000円・週末4,500円でした。中央値も最小も**この48件だけを数えた値**で、歩合や併用の案件は入っていません。

ここに出ている金額は、いずれも**出店者の側が負担する総額**です。仲介が入るときは手数料が差し引かれるので、会場側の受取はこれより少なくなります。

平日と週末の差は[平日の出店場所](/blog/weekday-food-truck-spots)に、金額の全体像は[出店料の相場](/blog/food-truck-fee-guide)に詳しく書きました。

## 出店料は誰が払うのか

4つ目の「出店料の形」です。**誰がお金を払うか**で3通りに分かれます。

1. **来場者が自分で買う形** … 負担はなく、逆に出店料を受け取る側になります。マルシェ、お祭り、学園祭など、もっとも多い形です
2. **売上保証** … 売上が一定額に届かなかった差額を負担します。社員向けや学校行事など、来場者が限られる場合に
3. **商品買取** … 無料で配る場合に、食数分を主催者が買い取ります

**集客が見込める催しなら、1番目の形で持ち出しは発生しません。** 2番目と3番目は主催者側に費用が出ます。目安は[キッチンカーを呼ぶ費用](/vendor/cost)で確かめてください。

受け取る側になる場合、決め方は固定・歩合・その併用と、金額を出さない応相談の4通りです。2026年9月6日時点の募集中110件では固定のみの52件が最も多く、歩合の率や税の書き方まで含めた内訳は[キッチンカーを無料で呼ぶには](/blog/invite-food-truck-free)にまとめました。

忘れやすいのが**税の扱い**です。「5,000円」とだけ書くと税込か税別かで後から食い違うので、募集要項に必ず添えてください。実際の書きぶりは[掲載中の募集案件](/places)で見られます。

## よくある質問

### キッチンカーは1台から呼べますか？

**1台からご相談いただけます。** 複数台を並べると賑わいは出ますが、同じ来場者数なら1台あたりの売上は分散します。台数は停められる区画から逆算してください。

### いつまでに相談すればよいですか？

**最低でも開催日の2週間前まで**が目安です。直前でも、空いている出店者が見つかれば手配できる場合があります。ただしこれは相談の最低ラインで、募集を出して選ぶところまで含めるなら早いほど選べます。**日程と場所が決まった時点**でご相談ください。

### 電源も水道もない場所ですが、呼べますか？

**呼べます。** 発電機を積んだ車両や、給排水タンクを備えた車両があります。困るのは、無いと伝えないまま当日を迎えることです。募集に「電源なし」「水道なし」と明記してください。

### 平日と週末で金額を変えるべきですか？

**変えるなら、平日を安くしてください。** 両方に金額を出している39件のうち、平日が安いのが25件、同額が14件、平日が高いのは0件でした（2026年9月6日時点）。同額でも構いませんが、週末を安くする設定は避けてください。

### 1回だけのイベントでも呼べますか？

**呼べます。** ただし2026年9月6日時点で募集中110件のうち、単発は13件で常設が97件です。単発は当日の売上が読みにくいぶん、想定来場者数とその数え方を伝えるなどの工夫が要ります。

