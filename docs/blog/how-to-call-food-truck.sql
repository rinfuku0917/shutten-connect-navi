募集を出す前に決めていただく項目です。この10項目が、そのまま募集要項になります。

| 項目 | 決めること |
|---|---|
| 搬入・搬出時間 | 入れる時間と、片づけの終了時間 |
| 電源 | 使えるか。使える場合の容量 |
| ガス機器 | 使用してよいか |
| 水道設備 | 使えるか |
| 飲食スペース | 座って食べられる場所の有無 |
