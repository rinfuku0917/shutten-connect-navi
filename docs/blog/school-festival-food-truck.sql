| 時期 | やること |
|---|---|
| 3か月前 | 学校の許可を取る。キッチンカーを置く場所と台数の上限を決める |
| 2か月前 | 出店料・時間・電源の有無・希望ジャンルを決めて募集を出す |
| 1か月前 | 出店者を決める。営業許可証と保険の書類を確認する |
| 2週間前 | 配置図、搬入時間、入構の手続きを出店者に伝える |
