- **PL保険に入っているか。** 売った食品で事故が起きたときの備えです

出店コネクトナビでは、営業許可証や保険証券を運営が確認しています。何を見ているかは[キッチンカー出店に必要な書類](/blog/kitchen-car-required-documents)をご覧ください。

気をつけたいのは模擬店です。**模擬店で食品を扱う場合は、模擬店の側で保健所への届け出や事前の相談が必要になります。** 催し全体の届け出を主催者に求める自治体もあります。模擬店の手続きで保健所に連絡するときに、「キッチンカーも入る」と伝えておくと確実です。

## 学園祭で喜ばれるキッチンカーの選び方

**模擬店とメニューを重ねないこと**が第一です。模擬店が焼きそばとフランクフルトなら、キッチンカーはケバブやクレープ、コーヒーに。重ねなければ、模擬店の売上も守れます。

次に**学生の財布に合う価格**です。応募してきた出店者のメニューと価格を見て選べます。

出店コネクトナビで**公開中の出店者は1,386店**です。ジャンルは食事603店・スイーツ512店・ドリンク478店で、**2つ以上のジャンルを持つ店が525店**あります（複数選択のため合計は登録数を超えます）。対応エリアに東京を入れている店は765店、埼玉548店、神奈川545店、千葉468店。**首都圏の学園祭なら、条件に合う車を選べる母数があります。**

台数の目安、ジャンルの組み合わせ、雨天時の決め方は、イベント全般に共通するので[イベントにキッチンカーを呼ぶには](/blog/how-to-invite-kitchen-car)にまとめています。

## 学園祭のあとは、平日のランチにつなげる

募集中の学校31件のうち、**28件は毎週や毎月決まった日に来てもらう常設**です。

学園祭で評判のよかった車に、平日の昼にも来てもらう。学食の混雑を分散させたい、選択肢を増やしたいという学校には、学園祭が最初の顔合わせになります。常設で入れるときの曜日と条件の決め方は[大学・専門学校の学食にキッチンカーを呼ぶ](/blog/campus-food-truck)に分けてまとめました。

## よくある質問

### 学園祭にキッチンカーを呼ぶと、費用はかかりますか？

**学校側の持ち出しは0円で呼べます。** 出店料は出店者から受け取るもので、学園祭の実例は「売上の15%＋税」です（2026年9月13日時点、出店コネクトナビ掲載の案件より）。

### 何か月前から準備すればよいですか？

**開催の3か月前**に学校の許可を取り、2か月前に募集を出すのが理想です。

### 保健所への届け出は必要ですか？

**学校がキッチンカーのために営業許可を取る必要はありません。** キッチンカーは自分で営業許可を持っています。模擬店で食品を扱う場合は、模擬店の側で届け出や相談が必要です。

### 1日だけ、1台だけでも来てもらえますか？

**来てもらえます。** 学園祭のような単発の催しも募集できます。台数は1台からご相談いただけます。

