## 学園祭にキッチンカーを入れると、ここが変わる

**食の目玉ができます。** 車両が並ぶだけで会場の空気が変わり、「キッチンカーが来る」は、それ自体が告知の見出しになります。

**模擬店の負担が減ります。** 火と食材を扱う模擬店は、衛生管理も準備も重い企画です。食事の中心をキッチンカーに任せれば、模擬店は得意なメニューに絞れます。

**昼の行列がさばけます。** キッチンカーは厨房を積んだ店舗そのものです。提供に慣れたプロが入るので、昼どきの混雑に強くなります。

**実行委員会の収入になります。** 出店料は、出店者から受け取るお金です。企画費や来年の予算に回せます。

## 【実データ】学校は最も多く掲載してきた場所

出店コネクトナビで**これまでに公開した306件（募集終了を含む）**のうち、**学校は130件**。場所の種類として最も多く、イベント・お祭りの46件を大きく上回ります（2026年9月13日時点）。学生と教職員が集まる場所は、キッチンカーにとって売上の立つ場所です。

いま**募集中の110件**に絞っても学校は31件。そのうち3件が、学園祭のような単発の催しです。

### 学園祭の実例は「売上の15%＋税」

募集中の学校31件の出店料は、**31件すべてが歩合**です。率は10%が29件、15%が2件。**15%の2件は、どちらも単発の催し**でした。

| 催しの実例 | 出店料 |
|---|---|
| 都内の専門学校の学園祭 | **売上の15%＋税** |
| 神奈川の学校を会場にした学会の大会（10:30〜16:00） | 売上の15%（税別） |

毎週のランチは10%が標準。一方で、学校の単発3件のうち2件が15%です。**学園祭は15%で条件を出せる催しです。** 学校の単発でも、都内の専門学校のように「売上の10%＋税」で出した例があります。

学校に限らず、募集中の単発イベント11件のうち6件が歩合です。

## 出店料は「売上の15%」から考える

歩合は、売れた分に応じて出店料を受け取る形です。**売れなければ出店者の負担も小さく、売れれば実行委員会の収入も増えます。持ち出しは0円です。**

学園祭は、天気や日程で来場者数が大きく動きます。学生向けの価格帯で、客単価も抑えめです。固定額にすると、出店者は赤字を心配して応募をためらいます。**歩合にすると、出店者は安心して手を挙げられます。** 学園祭に歩合が向くのはこのためです。

計算は単純です。たとえば1台の売上が1日5万円だったとします。15%なら出店料は7,500円（税別）。3台入れば2万2,500円です。※出店者が支払う額です。仲介を通す場合、受け取るのはここから手数料を引いた額になります。

招待制など来場者が限られる行事には、売上を下支えする形や食数分を買い取る形もあります。違いは[キッチンカーを呼ぶ費用](/vendor/cost)に、相場全体は[キッチンカーの出店料の相場](/blog/food-truck-fee-guide)にまとめています。

