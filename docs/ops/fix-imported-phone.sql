-- 旧サイトから取り込んだ名簿（imported_sellers）の電話番号を直す。
--
-- 経緯:
--   出店者情報のExcelに「47336013の冒頭は0から始まります。」と書かれた
--   セルが見つかった。調べたところ、その番号自体はDBに存在せず、
--   Excelが引用符付きの数字を数値と見なして先頭の0を落とすため、
--   人が注記を書き足したものと分かった。
--   CSV書き出し側は ="047..." の形に直した（app/admin/page.tsx）。
--   ここは、すでにDBに入ってしまった分の手当て。
--
-- 調査結果（2026-09-03 時点）:
--   profiles          … 電話あり99件、先頭0なし 0件（無事）
--                       数字以外まじり1件はテストアカウントの「テスト」
--   imported_sellers  … 電話あり1,385件、直すべきものが下記
--
-- imported_sellers はログインに使う会員データではなく、取り込み名簿。
-- 急ぎではないが、運営が移行組へ連絡するときに使う。
--
-- 実行記録（2026-09-03 実行済み）:
--   ⑵ 先頭の0が落ちた7件 … 7行更新。桁数も業態と合っていることを確認
--   ⑶ 全角を半角にそろえる … 5行更新。念のため桁数を数え、
--                            5件とも数字が落ちていないことを確認済み
--                            （PostgreSQL の translate は変換元が変換先より
--                              長いとあふれた文字を削除するため、全角変換の
--                              あとは必ず桁数を数えること）
--   ⑷ 手作業の2件         … 未対応

-- ============================================================
-- ⑴ 確認（先に流して、何がどう変わるか見る）
-- ============================================================
with x as (
  select id,
         coalesce(shop_name, rep_name, '(名前なし)') as 名前,
         phone as 現在,
         regexp_replace(
           translate(phone, '０１２３４５６７８９－ー−（）　', '0123456789---() '),
           '[^0-9]', '', 'g') as 数字
  from public.imported_sellers
  where coalesce(phone, '') <> ''
)
select 名前, 現在, 数字,
       case
         when 数字 = ''                                     then '×  数字が無い（手で直す）'
         when 数字 ~ '^0' and length(数字) between 10 and 11 then '○  直す必要なし'
         when length(数字) = 10 and 数字 ~ '^[789]'          then '→  0' || 数字
         when length(数字) = 9  and 数字 ~ '^[1-9]'          then '→  0' || 数字
         else '?  要確認'
       end as 判定
from x
where 数字 = '' or 数字 !~ '^0' or 現在 !~ '^[0-9-]+$'
order by 4, 1;

-- ============================================================
-- ⑵ 先頭の0が落ちた7件を直す
-- ============================================================
-- 半角数字だけの行に限り、10桁で7・8・9始まり（携帯）か9桁（固定）
-- のものだけを対象にする。7行返れば想定どおり。
--
--   スパイス                 363032322  → 0363032322
--   BONDY                   8011677827 → 08011677827
--   株式会社カレイドパンチ      8065123143 → 08065123143
--   Urban Asia Picnic       9016970826 → 09016970826
--   Pizza Wagon Licht&Luce  9044232493 → 09044232493
--   島んちゅcafe             9045863640 → 09045863640
--   三本松昭男               9064742629 → 09064742629

update public.imported_sellers
set phone = '0' || phone
where phone ~ '^[0-9]+$'
  and phone !~ '^0'
  and ((length(phone) = 10 and phone ~ '^[789]') or length(phone) = 9)
returning shop_name, rep_name, phone;

-- ============================================================
-- ⑶ 全角を半角にそろえる（番号自体は変えない・任意）
-- ============================================================
-- montresor / Y'sキュイジーヌ合同会社 / シフォンケーキ専門店Ringring /
-- まんぷくキッチンはらぺこちゃん の全角4件と、
-- はぴふわの末尾に付いた「」が取れる。

update public.imported_sellers
set phone = btrim(regexp_replace(
      translate(phone, '０１２３４５６７８９－ー−　', '0123456789--- '),
      '[^0-9\- ]', '', 'g'))
where phone ~ '[０-９－ー−　「」]'
returning shop_name, rep_name, phone;

-- ============================================================
-- ⑷ 手作業が要るもの（自動では直せない）
-- ============================================================
--   Holyバーベキュー … 電話番号欄に holybbq.1129@gmail.com が入っている
--   はぴふわ         … 0907206096 は10桁。090で始まるなら11桁のはずで1桁足りない
--
-- 対象を出すだけのSQL:
select coalesce(shop_name, rep_name, '(名前なし)') as 名前, phone
from public.imported_sellers
where coalesce(phone, '') <> ''
  and (
    phone !~ '[0-9]'                                              -- 数字が1つも無い
    or (phone ~ '^0[0-9]{9}$' and phone ~ '^0[789]0')              -- 携帯なのに10桁
  )
order by 1;
