価格が分かると、見た人は**客単価をその場で見積もれます。** 「昼に300食出る場所に、単価800円の車を呼べば売上はこのくらい」という計算ができます。**計算できる相手は、呼びやすい相手です。**

## 書類は「承認済み」まで進めておく

