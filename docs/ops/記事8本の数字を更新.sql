見落としやすいのが保険です。**保険自体は自動更新されていても、手元の証券のコピーは更新前のまま**というケースがあります。更新後の証券に差し替えて出してください。

### 2. 営業許可の管轄が、出店先と合っているか

**ここが見落とされがちです。** 営業許可が有効なのは、**許可を出した自治体の区域内だけ**です。全国どこでも使えるものではありません。

たとえば東京都で取った許可は都内では使えますが、**埼玉県の案件に出るには、埼玉県で取り直す必要があります。** 都道府県をまたぐなら、原則として出店先を管轄する保健所の許可が別に要ります。応募したい地域が決まったら、**先に管轄の保健所に確認**してください。

### 3. 記載が読み取れるか

撮影した写真が暗い、一部が切れている、光が反射して文字が読めない。文字が読み取れなければ、確認のしようがありません。

**四隅が入るように、正面から、明るいところで撮る。** これだけで防げます。

