### なぜスーパーは歩合にしないのか

歩合制は「売上の10％」のように、売れた分だけ受け取る方式です。一見すると公平ですが、スーパーで採用されにくい理由が3つ考えられます。**以下はデータではなく、条件の設計としての説明です。**

1. **売上の確認に手間がかかる。** 毎回いくら売れたかを報告してもらい、突き合わせる作業が発生します。店舗の業務にこれを足すのは現実的ではありません
2. **金額が読めない。** 固定なら年間の収入が計算できますが、歩合は天候で上下します
3. **キッチンカー側も嫌がらない。** スーパーは客足が読めるので、出店者から見ても固定のほうが有利になりやすい

**手間をかけずに、双方が納得しやすい。** これが固定制に集まる理由です。

