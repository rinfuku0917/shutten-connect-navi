## 写真がないと、何を売る車か分からない

いちばん効くのが写真です。**6割の店舗が1枚も載せていません。**

出店者ページに写真がないと、見た人は**どんな車が来るのか分からない**ままです。施設の景観を気にする商業施設や、学生の目に触れる学校では、これは通しにくい理由になります。

載せるべきは3種類です。

1. **車両の外観** … 正面から、全体が入るように。のぼりや装飾も含めて
2. **提供中の様子** … 販売している場面。にぎわいが伝わる
3. **商品** … 実際に出している料理。盛り付けが分かるもの

**プロの撮影は要りません。** 明るい時間に、スマホで、まっすぐ撮れば十分です。何も無い状態と比べれば、その差のほうがはるかに大きいからです。

