| **固定制**（1日◯円） | **31件** |
| 歩合制（売上の◯％） | 2件 |
| 応相談 | 1件 |

※募集要項に書かれた金額の書き方で数えました。

**9割が固定制**です。これは場所の種類によってはっきり違います。

### 場所の種類で決め方がまるで違う

同じ110件を場所の種類で分けると、こうなります。

| 場所 | 固定制 | 歩合制 | 併用 | 応相談 |
|---|---|---|---|---|
| スーパー（34件） | **31件** | 2件 | 0件 | 1件 |
| 商業施設（29件） | 17件 | 2件 | **8件** | 2件 |
| **学校（31件）** | — | **30件** | — | — |

※学校31件のうち、歩合制と数えられたのは30件です。残る1件は決め方の内訳が取れていないため「—」としています。

**学校は31件のうち30件が歩合制**でした。スーパーと商業施設は固定制が主で、**学校だけが正反対**です。

ただし、これは場所の性質というより**数社の方針の差**です。スーパー34件のうち32件はチェーン2社で、**固定31件は31件すべてがこの2社**。系列に属さない独立のスーパー2件は、**2件とも歩合制**でした。「スーパーは固定」は業態の必然ではなく、大手2社が本部で決めた条件を横展開した結果です。

もうひとつ、**「固定＋歩合」の併用は9件のうち8件が商業施設**です。スーパーには1件もありません。商業施設の条件の組み方は[商業施設でキッチンカーの催事を組むには](/blog/mall-food-truck-event)にまとめました。

学校は在籍者数から売上が読めそうに見えますが、長期休みや試験期間で客足が大きく振れます。**振れる場所は歩合、読める場所は固定**という説明はつきますが、上のとおり件数の大半は数社の方針で決まっています。

### なぜスーパーは歩合にしないのか

歩合制は「売上の10％」のように、売れた分だけ受け取る方式です。一見すると公平ですが、スーパーで採用されにくい理由が3つ考えられます。**以下はデータではなく、条件の設計としての説明です。**

1. **売上の確認に手間がかかる。** 毎回いくら売れたかを報告してもらい、突き合わせる作業が発生します。店舗の業務にこれを足すのは現実的ではありません
2. **金額が読めない。** 固定なら年間の収入が計算できますが、歩合は天候で上下します
3. **キッチンカー側も嫌がらない。** スーパーは客足が読めるので、出店者から見ても固定のほうが有利になりやすい

**手間をかけずに、双方が納得しやすい。** これが固定制に集まる理由です。

### 実際の出店料（出店者が払う額）

固定制の案件で、実際に設定されている金額です。

| 例 | 平日 | 週末 | 件数 |
|---|---|---|---|
| 首都圏のチェーンA | 3,000円 | 4,500円 | 16件 |
| 別業態に転換した1店舗 | 5,500円 | 7,500円 | 1件 |
| 茨城のチェーンB | 5,000円 | 5,000円 | 14件 |

※いずれも**出店者が支払う総額**です。仲介を通す場合、店舗の受取はここから手数料を引いた額になります。

**チェーンAは平日と週末で1,500円の差**をつけ、**チェーンBは均一**にしています。どちらも成立しています。

17店舗のうち1店舗だけ金額が高いのですが、これは別業態のディスカウントストアに転換した店舗でした。**業態が変われば条件も変えてよい**、という例です。

差をつける利点は、来客の多い週末にしっかり受け取れること。均一の利点は、条件が単純で説明が要らないことです。**運用に手をかけられないなら均一のほうが楽**です。

なお出店料の相場そのものは[キッチンカーの出店料の相場](/blog/food-truck-fee-guide)に、平日と週末の差は[平日の出店場所](/blog/weekday-food-truck-spots)にまとめています。

## 何を売る車を入れるか

ここを外すと、出店者も店舗も損をします。**売り場と競合しないこと**が第一条件です。

出店コネクトナビに登録している出店者のジャンルは、食事602店・スイーツ511店・ドリンク477店・物販36店です（複数選択のため合計は登録数を超えます）。母数は十分あるので、**選べます。**

| 相性 | ジャンル | 理由 |
|---|---|---|
| ◎ | クレープ、ドーナツ、たい焼き | 惣菜売り場に無い。買い物の前後に食べられる |
| ◎ | コーヒー、タピオカ、ジュース | 飲料は売り場と単価帯が違う |
| ○ | ケバブ、ホットドッグ | 温かい軽食。惣菜と時間帯をずらせば共存できる |
| △ | 弁当、唐揚げ、焼き鳥 | **惣菜売り場と正面から競合する** |
| △ | パン | ベーカリーがある店舗では避ける |

判断の基準はひとつです。**その商品が、店内で買えるかどうか。** 店内で買えるものを外で安く売れば、売り場の売上を食うだけです。

**買い物のついでに食べるもの、店内に無いもの**を入れてください。

## 系列店はまとめて募集する

34件の内訳を見ると、**チェーンAが17件、チェーンBが15件**。この2社で32件を占めます。

つまり**1店舗ずつ個別に交渉しているのではなく、系列全体でほぼ同じ条件を出している**ということです。これには理由があります。

- **条件を1回決めれば、全店舗で使える。** 店舗ごとに交渉する手間が消える
- **出店者が広がりやすい。** 1店舗で信頼された出店者に、近隣の系列店も任せられる
- **店舗間で比べられる。** 同じ条件なら、どの立地が向いているかが分かる

**最初の1店舗はテストです。** 3か月ほど回して、来客の反応と売上の変化を見てから、横に広げてください。

### まず1店舗、どこから始めるか

向いているのは次の条件がそろう店舗です。

- **駐車場に、動線を邪魔しない区画がある**（出入口から遠すぎない場所）
- **平日の昼か、週末の午後に来客の山がある**
- **近隣に住宅が接していない**（においと音の苦情が出にくい）

## 手続きと注意点

条件が決まったら、実務です。契約書に入れる項目、保険の確認、電源と給排水、近隣への説明。ここは駐車場全般に共通するので、[駐車場をキッチンカーに貸すには](/blog/renting-parking-space)に詳しくまとめました。

スーパー特有で気をつけたいのは**保健所への確認**です。キッチンカー事業者は自分で営業許可を持っていますが、**店舗の敷地内で継続的に営業させる場合、施設側にも確認が要ることがあります。** 管轄の保健所に一度聞いておいてください。

## よくある質問

### スーパーの駐車場の出店料は、いくらに設定されていますか？

募集中の案件では、**1日3,000〜5,000円の固定制**が中心です。首都圏のチェーンは平日3,000円・週末4,500円（16件）、茨城のチェーンは平日・週末とも5,000円（14件）で設定していました（2026年9月7日時点、出店コネクトナビ掲載の34件より）。**これは出店者が支払う出店料の総額です。** 仲介を通す場合、店舗が受け取るのはここから手数料を引いた額になります。

### 固定制と歩合制、どちらがよいですか？

スーパーなら**固定制**です。案件34件のうち31件が固定制でした。歩合は毎回の売上確認が必要で、店舗の業務が増えます。ちなみに**学校の案件は31件のうち30件が歩合制**で、場所の性質によって答えが変わります。

### どんなジャンルのキッチンカーを入れるべきですか？

**店内で買えないもの**です。クレープ、ドーナツ、コーヒーなどは惣菜売り場と競合しません。弁当や唐揚げは惣菜と正面からぶつかるため、売り場の売上を食う可能性があります。

### 何店舗から始めるべきですか？

**まず1店舗**です。募集中の案件でも、チェーンは同じ条件を系列全体に展開しています。1店舗で3か月ほど試し、来客の反応を見てから広げるのが安全です。

### 単発のイベントとして呼ぶこともできますか？

できますが、募集中のスーパー案件**34件はすべて常設**でした。スーパーの駐車場に来るのはもともと買い物客なので、1回では覚えてもらえません。**毎週同じ曜日に出す形**のほうが効果が出ます。

