## 依頼する側が何を見ているか

まず、選ぶ側の画面がどうなっているかを説明します。

見られ方は2通りあります。

**1つは、応募したときの一覧です。** 運営の画面には、応募者ごとに**店名・ジャンル・対応エリア・書類の状況**（承認済み／審査中／未提出）が並びます。募集者の画面には**出店者名と希望日**が出ます。

