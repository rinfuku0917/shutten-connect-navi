## 出店場所を探す6つの方法

ここからは探し方です。それぞれ手間と成功率が違います。

### 方法1：マッチングサービスを使う

出店場所を探している施設と、出店したいキッチンカーをつなぐサービスです。**掲載されている条件（出店料・曜日・台数など）を、問い合わせる前にまとめて確認できる**のが、他の方法との決定的な違いです（出店料は無料の会員登録後に表示されます）。

自分で探して交渉する方法は、どれも「連絡先を調べる → 話を聞いてもらう → 条件を詰める」という手順を毎回くり返します。**開業したばかりで実績も人脈もない段階では、ここで止まります。**

### 方法2：施設に直接交渉する

スーパー、ホームセンター、商業施設に自分で持ちかける方法です。うまくいけば競合が少なく、条件も直接決められます。

窓口は店舗ではなく本部の担当部署であることが多く、店長に話しても決まらないのが普通です。**チェーン店ほど本部の判断が要ります。** 実績（過去の出店写真、保健所の許可証、保険の加入証明）をまとめた資料を先に用意しておくと話が早く進みます。

### 方法3：イベント主催者に応募する

お祭り、音楽フェス、マルシェ、スポーツ大会などです。1日で普段の何倍も売れることがあり、キッチンカーの花形と言われます。

ただし先に見たとおり、**募集の数は上位3つの5分の1以下（110件中7件）**というのが実情です。人気イベントは応募が集中し、選ばれるにはメニュー写真や実績の見せ方が要ります。**イベントだけを狙うと、出られない週が続きます。**

### 方法4：公園・道の駅など公共スペース

自治体が管理する公園や広場です。休日は家族連れが集まり、客層も幅広くなります。

**手続きに時間がかかる**点は覚悟が必要です。都市公園での営業には占用許可などの申請が要り、名称も条件も自治体ごとに違います。人気の公園は抽選になることもあります。管轄の役所か公園事務所に、出店したい日の**数か月前**に問い合わせてください。

### 方法5：オフィス・事業所に入る

平日のランチを狙う方法です。働く人は短時間で食事を済ませたいので、キッチンカーと相性が良く、**従業員数からおおよその食数が読める**のも利点です。

福利厚生としてキッチンカーを呼ぶ会社が増えています。窓口はビルの管理会社か、企業の総務です。

### 方法6：SNS・同業者のつながり

「あの場所が空いた」「このイベントが募集している」という話は、実際にキッチンカー仲間のあいだで回っています。SNSで出店情報を発信していると、施設側から声がかかることもあります。

ただし**これは実績ができてから機能する方法**です。開業当初から当てにはできません。まず1〜3で実績を作り、そこから広げるのが順序です。

## 開業直後に現実的なのはどれか

6つ挙げましたが、**始めたばかりの人が最初の1か所を決めるなら、方法1と方法2の2つ**です。

方法3（イベント）は募集の数が少なく、方法4（公園）は手続きに数か月かかります。方法6（つながり）は実績が前提です。**最初の出店を待っているあいだにも、車の維持費はかかり続けます。**

現実的な進め方はこうです。

1. **常設の募集に応募して、まず1か所を確保する**（募集の88％はここ）
2. その場所で2〜3回出て、**自分のメニューが1日何食売れるかを記録する**
3. 数字が見えたら、**出店料の条件で場所を選び直す**（[出店料の相場はこちら](/blog/food-truck-fee-guide)）
4. 平日は常設、休日はイベント、と**組み合わせて営業日を埋める**

平日に入れる場所は[キッチンカーの平日の出店場所](/blog/weekday-food-truck-spots)に、応募で選ばれるための準備は[出店依頼をもらうには](/blog/get-food-truck-offers)にまとめています。

順番が大事です。売上の見込みが立たないうちに条件の重い場所を取ると、天候が崩れただけで赤字になります。

なお、**応募自体は登録すればできますが、選ばれるには書類が要ります。** 営業許可証やPL保険など6種類が必須で、そろえるのに時間がかかるものもあります。良い募集が出てから慌てないよう、**先に通しておく**のが確実です（[キッチンカーの出店に必要な書類](/blog/kitchen-car-required-documents)）。

## 場所の種類ごとの向き・不向き

| 場所 | 向いているメニュー | 気をつける点 |
|---|---|---|
| スーパー・食品店 | 惣菜、弁当、パン、スイーツ | 夕方の買い物客が中心。生鮮売り場と競合しない品ぞろえに |
| 学校・専門学校 | ランチ、丼もの、麺類 | 長期休みは客が消える。学事日程の確認が要る |
| 商業施設・モール | スイーツ、ドリンク、軽食 | 集客力は高いが条件のハードルも高め |
| オフィス・事業所 | ランチ、弁当 | 平日昼のみ。食数が読みやすい |
