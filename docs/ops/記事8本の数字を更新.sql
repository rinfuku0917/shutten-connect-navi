## 歩合と固定、どちらを選ぶべきか

判断の基準はひとつです。**その日の売上見込みが、損得の分かれ目を超えるかどうか。**

分かれ目は割り算で出ます。

> 分かれ目の売上 ＝ 固定の出店料 ÷ 歩合の料率

たとえば固定5,000円と歩合10％で迷っているなら、5,000円 ÷ 0.1 = **50,000円**が分かれ目です。

- 1日の売上が5万円**を超える**見込み → **固定のほうが手取りが多い**
- 1日の売上が5万円**に届かない** → **歩合のほうが手取りが多い**

