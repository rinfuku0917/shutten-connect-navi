商業施設にはテナントの飲食店やフードコートが入っています。館内で買えるものを外で安く売れば、テナントの売上を食うだけです。**テナントから苦情が出ると、催事そのものが続かなくなります。**

- ラーメン、カレー、丼もの … **フードコートと正面からぶつかる**
- クレープ、コーヒー、生ジュース … 館内に無いことが多く、持ち歩けるので回遊も止めない

売り場との競合の考え方は[スーパーの駐車場にキッチンカーを誘致するには](/blog/supermarket-food-truck)に詳しく書きました。

## 何台から始めるか

**まず1台**をおすすめします。

複数台を並べると賑わいは出ますが、1台あたりの売上は下がります。**売上が下がると、次から来てくれません。** 良い出店者を確保するほうが、台数を増やすより効きます。

3か月ほど1台で回して、来客の反応と売上を見てから増やしてください。判断の材料はこの3つです。

1. **行列ができているか** … できていれば台数を増やす余地がある
2. **テナントから苦情が出ていないか**
3. **出店者が続けて入りたいと言っているか** … 言われなければ条件が合っていない

## 手続きと注意点

契約書に入れる項目、保険の確認、電源と給排水、近隣への説明。ここは駐車場を貸す場合と共通するので、[駐車場をキッチンカーに貸すには](/blog/renting-parking-space)にまとめました。

商業施設で特に気をつけたいのは**消防法まわり**です。屋内や屋根のある場所で火気を使う場合、消防署への届出や、消火器の配置が求められることがあります。**設置場所が決まった時点で、管轄の消防署に相談**してください。

スーパーの駐車場に入れる場合の条件設計は[スーパーの駐車場にキッチンカーを誘致するには](/blog/supermarket-food-truck)にあります。

## よくある質問

### 商業施設の催事は、単発と常設のどちらがよいですか？

**常設です。** 募集中の商業施設29件は、すべて常設でした（2026年9月7日時点）。単発は告知の手間がかかるうえ、終われば元に戻ります。毎週同じ曜日に出すほうが「その日に行く理由」になり、出店者も続けて入ってくれます。

### 出店料はいくらに設定すればよいですか？

固定なら**1日5,000〜8,000円**が中心です。曜日で分ける場合は平日4,500〜7,000円・週末6,500〜9,000円。併用なら**3,000円＋売上の15％**が最も多い設定でした。**これは出店者が支払う総額**で、仲介を通す場合は手数料を引いた額が受取になります。

### 固定と歩合、どちらにすべきですか？

商業施設では**併用がよく使われています。** 募集中29件のうち8件が併用で、スーパー34件と学校31件には0件でした。ただしこれは場所の性質というより数社の方針で、商業施設29件のうち23件が同じ系列です。来客の振れ方で決めてください。運用の手間を減らすなら「3,000円＋15％」のような足し算型が扱いやすいです。

### どんなジャンルを入れるべきですか？

**館内で買えないもの**です。クレープやコーヒーはフードコートと競合しにくく、持ち歩けるので回遊も止めません。ラーメンや丼ものはフードコートと正面からぶつかり、テナントから苦情が出ます。

### 何台くらい入れられますか？

**まず1台**から始めてください。台数を増やすと1台あたりの売上が下がり、出店者が続けて来なくなります。3か月ほど様子を見て、行列ができるようなら増やす、という順序が安全です。

