## 平日に出られるのはどんな場所か

場所の種類ごとの件数は[キッチンカーの出店場所の探し方](/blog/kitchen-car-location-guide)にまとめています。ここでは**平日に強い場所**だけを見ます。

答えは**学校とオフィス**です。理由がはっきりしています。

### 学校・専門学校（31件）

学内のランチ需要です。**学校系31件のうち26件が常設**で、毎週決まった曜日に入る形が中心です。

- **客数が読める。** 在籍者数から、おおよその食数が見積もれます
- **リピーターがつく。** 毎週同じ場所に通うので、2回目以降は売上が安定します
- **長期休みは客が消える。** 夏休み・春休みの分は、別の場所で埋める必要があります

学事日程の確認は必須です。**試験期間や休講日も客足が落ちます。**

