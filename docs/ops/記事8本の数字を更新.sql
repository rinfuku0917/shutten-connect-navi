**ひとつ注意があります。** ここに出ている金額は、募集要項に書かれた「**キッチンカーが払う出店料**」です。仲介を通す案件では、この中から手数料が引かれた額が場所側の受取になります（例：平日3,000円の案件で、場所側2,000円・運営1,000円）。**ご自身で直接募集する場合は、全額が受取額です。**

### 固定と歩合、貸す側はどちらを選ぶべきか

**売上が読めない最初のうちは歩合、実績が見えてから固定**が無難です。

歩合なら、来客が少なかった日に相手の負担が軽くなるので、続けてもらいやすくなります。固定は収入が読める代わりに、売れない場所だと相手が離れます。**1日で埋まらない枠を作るより、少額でも続けて入ってもらうほうが、年間では収益が大きくなります。**

実際の募集でも、常設の案件97件のうち48件が固定制、36件が歩合制と分かれています。

**スーパーの駐車場を貸す場合は、話が少し変わります。** 募集中のスーパー34件は31件が固定制で、歩合はほとんど使われていません（[スーパーの駐車場にキッチンカーを誘致するには](/blog/supermarket-food-truck)）。

## 貸す前に確認すること

### 土地の用途と契約の確認

最初に確認すべきは、その駐車場でキッチンカーの営業ができるかどうかです。

- 用途地域と建築基準法上の制限
- 賃貸物件の場合、賃貸契約に「駐車場以外の用途禁止」の条項がないか
- 管理組合や地主への事前相談・承認
- 自治体の条例による制限

**賃貸で借りている駐車場を貸すのは、又貸しにあたる可能性があります。** 必ず貸主の承諾を、書面で得てください。あとから発覚するとトラブルになります。

火気を扱う車両のため、消防設備や避難経路について**管轄の消防署に事前相談**しておくと確実です。

### 保健所への届出が要るかどうか

キッチンカー事業者は自分で保健所の営業許可を取っています。ただし**出店の形によっては、場所を貸す側にも届出が求められる場合があります。** 「臨時営業」として扱われるとき、主催者名義の届出が必要になることがあるためです。

多くの場合は事業者側の許可で足りますが、地域や運用のしかたで変わります。管轄の保健所に「駐車場の一角で定期的にキッチンカーを受け入れる場合、こちら側の手続きは必要か」と確認しておくと安心です。

## 契約書に入れる項目

口頭の合意だけでは、後で困ります。簡単なもので構わないので、書面を交わしてください。

- **貸す範囲** … 駐車スペース何番と何番の2台分、と場所を明示する
- **利用できる日時** … 毎週火・木曜日 11:00〜14:00、と具体的に
- **料金と支払い方法・期日** … 固定か歩合か、歩合なら売上の確認方法も
- **契約期間と、更新・解約の条件** … 解約は1か月前の通知、など
- **設備の使用範囲** … 電源、水道、ゴミ処理
- **禁止事項** … 騒音、におい、指定場所以外での営業
- **原状回復の義務**
- **損害賠償責任の所在**

契約期間は、**最初の1〜3か月を試行期間**として、問題がなければ更新する形にしておくと、お互いに動きやすくなります。

### 責任の範囲をはっきりさせる

どこまでが貸す側の責任かを決めておきます。一般的な線引きはこうです。

- **事業者の責任** … 営業そのものに起因する事故（食中毒、調理中の火災、商品のトラブル）、車両による施設の破損
- **貸す側の責任** … 駐車場の設備不良に起因する事故

「近隣からの苦情がくり返される場合は契約を解除できる」という条項も入れておくと、いざというとき動けます。

## 保険の確認

キッチンカーの営業では、食中毒、火災、第三者への損害といったリスクがあります。**契約前に、事業者の保険加入を必ず確認してください。**

- **PL保険（生産物賠償責任保険）** … 食中毒などによる損害を補償。食品を扱う以上、必須です
- **施設賠償責任保険** … 営業中の事故で第三者に与えた損害を補償
- **自動車保険** … 営業使用が補償の範囲に入っているか
- **火災保険** … 車両火災による周辺への被害

**保険証券のコピーを提出してもらい、補償内容と補償金額（最低でも1億円程度）、有効期限を確認します。** 更新のたびに証明書を出し直してもらう仕組みにしておくと、切れたまま営業されるのを防げます。

### 出店者側がどこまでそろえているか

出店コネクトナビでは、出店者に**6種類の書類（運転免許証の表裏、食品衛生責任者証、営業許可証、損害賠償保険証書、PL保険証券）を必須**として、1件ずつ審査しています。何をどう見ているかは[キッチンカーの出店に必要な書類](/blog/kitchen-car-required-documents)に書きました。

**個人で受け入れる場合は、この確認をご自身で行うことになります。** どの書類のどこを見ればよいかの参考にしてください。

### 貸す側の保険も見直す

施設所有者としての賠償責任保険に入っている場合でも、**キッチンカーの受け入れが補償の範囲に入っているとは限りません。** 保険会社に「駐車場の一部を飲食販売の目的で貸し出す」と伝え、必要なら契約を見直してください。

## 設備をどこまで用意するか

### 電源

キッチンカーの多くは、冷蔵庫や調理機器のために100Vまたは200Vの電源を使います。

- 提供できる電気容量（一般に15A〜30A程度）
- 電気料金の負担方法
- 延長コードやコンセントの管理責任
- 漏電ブレーカーの設置

電気料金は**定額（1日500円〜1,000円程度）にするか、メーターを付けて実費精算するか**を先に決めます。実際の募集でも「水道光熱費1,000円（使わなければ不要）」のように、出店料とは別に明記している例があります。

電源を出せない場合は、発電機の持ち込みになります。**その場合は低騒音型を使ってもらう**よう条件に入れてください。発電機の音は苦情の原因になりやすい項目です。

### 給排水

キッチンカーには給水・排水タンクが積まれていますが、長時間の営業では補給や処理が必要になります。水道設備がある場合は、使えるかどうかと条件を明示してください。

**排水は、下水への直接排水は認めず、タンクでの回収を基本に。** 不適切な排水は悪臭やつまりの原因になります。

### ゴミ

営業後のゴミは事業者が持ち帰る、を原則にします。ルールを決めておかないと、駐車場のゴミ箱に置いていかれることがあります。契約書か利用規約に**「すべてのゴミは事業者が持ち帰る」と明記**し、守られなかった場合の扱いも決めておいてください。

## 安全と近隣への配慮

### 動線

キッチンカーが入ると、駐車場内の人の流れが変わります。

- 出店場所と駐車車両の動線が交錯しないか
- 消防法上の緊急車両の進入路を確保できているか
- お客様の待機スペースは足りるか
- 看板やのぼりが視界を妨げないか

**営業開始前に、事業者と現地で配置を確認してください。** 図面だけでは分からない問題が見つかります。

### 近隣への事前説明

周辺に住宅やテナントがあるなら、先に一言伝えておくだけでトラブルが減ります。「毎週水曜の昼、駐車場の一角でキッチンカーが営業します」程度の内容で構いません。マンションやオフィスビルが近い場合は、管理組合や管理会社にも説明しておきます。

起こりやすいのは次の4つです。

| 起こること | 防ぎ方 |
|---|---|
| 発電機の騒音 | 低騒音型の使用、または外部電源の提供 |
| 調理のにおい | 揚げ物の扱いを事前に相談。風向きを見て配置する |
| ゴミの散乱 | ゴミ箱の設置と、事業者による回収を条件にする |
| 駐車場の混雑 | 購入客の待機場所を決める。規模によっては誘導を依頼 |

苦情が出たときの連絡先と対応の流れも、先に決めておいてください。

## 始めたあとにやること

### 初回は立ち会う

**初めて営業する日は、できるだけ現場を見てください。** 契約どおりの場所か、清掃や片付けは適切か。問題があればその場で伝えるほうが、あとから直してもらうより早く済みます。

### 定期的に確認する

- 契約どおりの時間・場所で営業しているか
- 清掃と原状回復が適切か
- 近隣からの苦情はないか
- 保険の有効期限は切れていないか

