|---|---|---|
| 3,000円 | 30,000円 | 20,000円 |
| 5,000円 | 50,000円 | 33,333円 |
| 7,500円 | 75,000円 | 50,000円 |

**初めて出る場所なら歩合、売上が読めている常連の場所なら固定**、というのが素直な選び方です。

