### 歩合と固定はどちらが得ですか？

その日の売上によります。**「固定額 ÷ 料率」で計算した金額を売上が超えるなら固定が得**です。固定5,000円と歩合10％なら、売上5万円が分かれ目になります。売上が読めない場所は歩合、読める場所は固定が無難です。

### 出店料が無料の場所はありますか？

出店料をとらない募集もありますが、多くは主催者側に別の目的があります。集客の一環として呼ぶケースや、売上の一部を別の形で扱うケースです。**無料という条件だけで選ばず、その日に何台入るのか、どれだけ人が通るのかを必ず確認してください。**

### 出店料以外に費用はかかりますか？

案件によって、光熱費・駐車場代・消費税・広告オプションが別途かかります。募集要項に併記されていることが多いので、応募前に確認してください。

