import { NextResponse } from 'next/server'

// 出店者からの申込の取り消しは受け付けない。
//
// 以前はここで、審査中の申込だけを取り消せるようにしていた
// （承認済みは409で拒否していた）。それをやめ、状態にかかわらず断る。
//
// 理由:
//   気軽に取り消せると、当日の欠席が増えてしまう。
//   募集者は会場や提出書類の準備を進めており、
//   直前の取り消しはそのまま募集者の損害になる。
//   やむを得ない事情かどうかは、運営が個別に判断する。
//
// 出店者の画面からも取り消しのボタンを外しているが、
// ここでも断っている。申込まわりは画面から直接データベースへ
// 書き込む作りで、画面側の制御は「押しにくくする」だけにしかならないため。
//
// 運営が取り消す口は別にある（/api/applications/cancel-approved）。
// そちらは運営だけが呼べて、売上や請求がある出店は取り消せない。
//
// この窓口を消さずに残しているのは、古い画面が端末に残っていても
// 「取り消せた」と誤解させず、連絡先を案内できるようにするため。

const ADMIN_EMAIL = 'info@connect-navi.com'

export async function POST() {
  return NextResponse.json(
    {
      error: '申込の取り消しは、この画面からは行えません。'
        + 'お手数ですが、運営（' + ADMIN_EMAIL + '）までご連絡ください。',
    },
    { status: 409 },
  )
}
