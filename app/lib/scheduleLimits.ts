// 案件の日程（places.schedule）に入れられる日数の上限。
//
// ここが唯一の正で、次の3か所が同じ数を読む：
//   ・app/dashboard/host/new-place/page.tsx        … 募集者・運営の入力
//   ・app/dashboard/host/edit-place/[id]/page.tsx  … 同上
//   ・app/api/cron/monthly-schedule/route.ts       … 毎月1日の自動追加
//
// なぜ31日だったか:
//   1か月ぶんを入れる想定で始めたため。データベース側の制約ではなく、
//   こちらで決めた数（places.schedule は jsonb で長さの制限が無い）。
//
// なぜ90日にしたか（2026-10-02 の運営からの依頼）:
//   「1か月先までしか設定できない」という相談を受けた。
//   実際の制約は「1か月」ではなく「合計31日まで」で、
//   火・木・金の案件なら約2.4か月ぶん入っていた（茨城女子短期大学は24日）。
//   それでも、毎日出る案件では1か月で埋まってしまう。
//   2〜3か月先まで募集を出せるようにしたいという要望に合わせて90日にした。
//
// 90日にしても壊れないことの確認:
//   ・places.schedule に長さの制約は無い（2026-10-02 に本番で確認）
//   ・毎月1日の自動追加は、過ぎた日を外してから足すので上限に当たりにくい
//   ・出店者の申込カレンダーは月ごとに描くので、日数が増えても1画面は長くならない
//
// 上げるときに一緒に見るところ:
//   ・申込の下限（min_apply_days）と日数ごとの金額（day_count_fees）の
//     入力欄は max=31 のままにしている。「1回の申込で何日選ぶか」の話で、
//     案件が何日ぶん日程を持てるかとは別のため
//   ・事前請求でまとめられる日数（app/api/admin/invoice/route.ts）も31のまま。
//     1枚の請求書に入れる出店日の数で、これも別の話
export const MAX_SCHEDULE_DAYS = 90
