// 取り消した申込を、出店者の画面に出すかどうか。
//
// 答えは「出さない」。
//
// 経緯:
//   1. はじめは行を残し（status='cancelled'）、出店者の画面にも出していた。
//      本人の画面に何年も残るのは気持ちのよいものではない、という指摘を受けて、
//      30日を過ぎたものだけ隠すようにした。
//   2. その30日の決まりを出店者のマイページにしか入れておらず、
//      案件ページの「この案件はエントリー済みです」には入れ忘れた。
//      取り消した申込がいつまでも「エントリー済み・審査中」として出ていた。
//   3. 運営の判断で、取り消したら行ごと消すことにした
//      （app/api/applications/cancel-approved/route.ts）。
//      消せば画面にも出ないので、30日の猶予そのものが要らなくなった。
//
// それでも、この判定を残している理由:
//   削除が失敗することがある（messages を消せなかった、など）。
//   そのときは status='cancelled' の行が残る。残った行を出店者に見せると、
//   消せたときと見え方が食い違う。どちらでも同じ見え方になるよう、
//   出店者の画面では取り消しをいっさい出さない。
//
//   消せた場合は、運営の画面にも出ない（行が無いため）。
//   キャンセル料の判断と繰り返す出店者の把握は、
//   purge_log の控え（app/lib/purgeLog.ts）でおこなう。
//   残ってしまった行だけは、運営の応募者一覧に取消しとして見える。
//
// 同じ判定を画面ごとに書くと、また片方だけ直して食い違う。ここを唯一の正とする。
//
// 使う側:
//   app/dashboard/seller/page.tsx            … 出店者のマイページの申込一覧
//   app/places/[id]/PlaceDetailClient.tsx    … 案件ページの「エントリー済み」

/**
 * この申込を、出店者の画面に出してよいか。
 * 取り消したものは出さない。それ以外（審査中・承認済・不採用）は出す。
 */
export function showsToSeller(app: { status?: string | null }): boolean {
  return app?.status !== 'cancelled'
}
